def normalize(text: str) -> str:
    """Приведение строки конспекта и якоря к одному виду.

    `й` → `и` наравне с `ё` → `е`, и это **починка дефекта, а не удобство**
    (2026-08-13). Якоря писались руками, и в них десятки групп набраны с `и` там,
    где в тексте стоит `й`: `первои трети`, `уровня взаимодеис`, `меикап-каталог`,
    `пресеил`, `лишнии клик`. Без свёртки такая группа не срабатывает **никогда** —
    проверено по всем конспектам в `out/`: `первои трети` 0 совпадений против 68 у
    `первой трети`, `меикап` 0 против 83 у `мейкап`. Ни один пункт не терял все свои
    группы, поэтому дефект не обнулял счёт, но занижал его: ровно этим объясняется
    расхождение ручной сверки по D7, где «уровням взаимодействия» стоит в конспекте,
    а якорь `уровня взаимодеис` на него молчал.

    Починка сделана одной строкой и **ни один якорь не тронут** — иначе это была бы
    подгонка по пунктам. Арбитр — ручная разметка, снятая до этой правки: `--calibrate`
    обеих встреч после свёртки не хуже (84/84 и 46/48).
    """
    return (text.lower().replace("ё", "е").replace("й", "и")
            .replace("*", " ").replace("«", " ").replace("»", " "))


def claim_lines(recap: str) -> list[str]:
    """Строки, в которых договорённость может стоять: всё, кроме «Итога»."""
    lines, skipping = [], False
    for line in recap.split("\n"):
        heading = re.match(r"^##\s+(.+?)\s*$", line)
        if heading:
            skipping = heading.group(1).strip().lower() in SKIP_SECTIONS
            continue
        if not skipping and line.strip():
            lines.append(normalize(line))
    return lines


def found(recap: str, meeting: str = DEFAULT_MEETING) -> dict[str, bool]:
    lines = claim_lines(recap)
    result = {}
    for item, groups in MEETINGS[meeting][0].items():
        result[item] = any(
            all(word in line for word in group)
            for group in groups
            for line in lines
        )
    return result


def score(recap: str, meeting: str = DEFAULT_MEETING) -> int:
    return sum(found(recap, meeting).values())


def calibrate(meeting: str = DEFAULT_MEETING) -> int:
    anchors, hand, cells = MEETINGS[meeting]
    if not cells:
        print(f"встреча {meeting}: ручной разметки ячеек ещё нет — сверять не с чем.\n"
              f"Числам матчера по ней верить нельзя, пока она не снята.")
        return 1
    items = list(anchors)
    total = len(items) * len(cells)
    print(f"сверка матчера с ручной разметкой · встреча {meeting} · {total} оценок\n")
    head = f"{'пункт':6}" + "".join(f"{k:>4}" for k in cells)
    print(head + "   расхождения")
    wrong = 0
    per_cell = {k: 0 for k in cells}
    for item in items:
        row = f"{item:6}"
        notes = []
        for key, (path, _) in cells.items():
            got = int(found((HERE / path).read_text(encoding="utf-8"), meeting)[item])
            want = hand[item][key]
            row += f"{('да' if got else '—'):>4}"
            if got != want:
                wrong += 1
                per_cell[key] += 1
                notes.append(f"{key}: матчер {got}, рука {want}")
        print(row + "   " + "; ".join(notes))
    print(f"\nсовпало {total - wrong} из {total} ({(total - wrong) / total * 100:.0f} %)")
    if wrong:
        print("по ячейкам:", {k: v for k, v in per_cell.items() if v})
    return 0 if wrong <= 4 else 1


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("recap", nargs="?", type=Path)
    ap.add_argument("--dir", type=Path, default=None, help="каталог с recap.md внутри подкаталогов")
    ap.add_argument("--calibrate", action="store_true")
    ap.add_argument("--meeting", default=DEFAULT_MEETING, choices=sorted(MEETINGS))
    args = ap.parse_args()

    if args.calibrate:
        return calibrate(args.meeting)
    if args.recap:
        hit = found(args.recap.read_text(encoding="utf-8"), args.meeting)
        print(f"{sum(hit.values())}/{len(hit)}: " + " ".join(k for k, v in hit.items() if v))
        return 0
    if args.dir:
        base = args.dir if args.dir.is_absolute() else HERE / args.dir
        for path in sorted(base.glob("*/recap.md")):
            hit = found(path.read_text(encoding="utf-8"), args.meeting)
            print(f"{path.parent.name:24} {sum(hit.values()):2}/{len(hit)}  "
                  + " ".join(k for k, v in hit.items() if v))
        return 0
    ap.print_help()
    return 1


