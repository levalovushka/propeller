def names() -> owners.Names:
    return owners.Names.of(FIXTURE_TRANSCRIPT)


def test_owner_kept() -> None:
    person = names()
    for slot in ("**Левон** — соберёт макеты", "**Оля** — посчитает смету",
                 "**Влад Шукуров** — закроет камуфляжи",
                 "**Настя Кузнецова** — вернётся из отпуска"):
        check(f"исполнитель сохранён: {slot[:24]}", owners.scrub(slot, person), slot)


def test_owner_cut_keeps_text() -> None:
    person = names()
    cases = {
        # выдуманная фамилия: пары «Илья Сафронов» на встрече не было
        "**Илья Сафронов** — упакует план": "упакует план",
        # wrongname: оба токена честные порознь, пары нет
        "**Саша Шукуров** — закроет заакт": "закроет заакт",
        # коллектив вместо человека
        "**Команда VK Музыка (дизайн)** — разработает решение": "разработает решение",
        # сырой ярлык расшифровки
        "Speaker S1 посчитает итоговые цифры": "посчитает итоговые цифры",
        "**Speaker S1** — подготовит тексты": "подготовит тексты",
    }
    for item, want in cases.items():
        check(f"слот срезан, текст цел: {item[:28]}", owners.scrub(item, person), want)


def test_owner_filter_does_not_eat_prose() -> None:
    """Пункт без слота исполнителя — с тире внутри фразы — не должен трогаться."""
