"""Фикстуры сборки: формы экстрактора, слияние прозы, слот исполнителя, артефакты.

Почему это единственный тест в лаборатории. Разбор форм экстрактора ломался
**четырежды**, каждый раз новой формой одного и того же ярлыка:

    1) `ДОГОВОРИЛИСЬ: раз; два; три` одной строкой — склеивалось в один пункт;
    2) `ДОГОВОРИЛИСЬ:` и буллеты следом — терялось целиком;
    3) строка-продолжение без буллета — терялась;
    4) `- ДОГОВОРИЛИСЬ: раз; два` — метка внутри буллета: строка уезжала в конспект
       **дословно, с ярлыком**, в чужую секцию (16 таких строк в code-ячейках m2,
       читаемость 1/5 — судейский аудит, `judge/JUDGE.md`).

Каждая форма — фикстура ниже. Пятая найдётся, но не молча: тест падает, а не выдаёт
ярлык пользователю.

Тем же порядком закрыт четвёртый дефект, найденный пере-судом (`judge/JUDGE-2.md`) —
артефакты генерации. У него своя ловушка: фильтр обязан **не трогать** «Fast Play»,
«Радио/VK» и «сбербанк.ru», иначе он срежет термин, на котором стоит якорь матчера.
Поэтому «что сохранено» здесь фикстур не меньше, чем «что срезано».

    python3 test_parse.py
"""

from __future__ import annotations

import sys

import bench_ensemble as b
import chunked
import owners

FAILED: list[str] = []


def check(name: str, got, want) -> None:
    if got != want:
        FAILED.append(f"{name}\n     получено: {got!r}\n     ожидалось: {want!r}")


# ---------------------------------------------------------------------------
# Формы экстрактора
# ---------------------------------------------------------------------------

def test_inline_list() -> None:
    """Форма 1: метка и список через точку с запятой одной строкой."""
    items = b.items_from_facts(
        "ДОГОВОРИЛИСЬ: каталог остаётся единым; корзина не меняется; главную переделываем")
    check("форма 1 · три пункта из одной строки", items["Решения"],
          ["каталог остаётся единым", "корзина не меняется", "главную переделываем"])


def test_label_then_bullets() -> None:
    """Форма 2: метка строкой, буллеты следом."""
    items = b.items_from_facts(
        "ЗАДАЧА:\n- Оля посчитает смету сегодня вечером\n- Левон проверит тексты завтра")
    check("форма 2 · буллеты под меткой", items["Задачи"],
          ["Оля посчитает смету сегодня вечером", "Левон проверит тексты завтра"])


def test_continuation_line() -> None:
    """Форма 3: продолжение без маркера буллета."""
    items = b.items_from_facts(
        "ОТКРЫТО: куда девать карусель акций\nсколько шагов в чекауте на самом деле")
    check("форма 3 · строка-продолжение", items["Открытые вопросы"],
          ["куда девать карусель акций", "сколько шагов в чекауте на самом деле"])


def test_label_inside_bullet() -> None:
    """Форма 4 (регресс из JUDGE.md): метка внутри буллета.

    Проверяется и то, что пункты разошлись по своим секциям, и то, что ярлык не попал
    в текст ни одного пункта.
    """
    facts = (
        "ОТКРЫТО: оценка функционала для раздела декоративной косметики\n"
        "- ДОГОВОРИЛИСЬ: отпустить Левона на клиентскую работу; два плана оценки\n"
        "- ЗАДАЧА: Оля посчитает итоговые цифры сегодня или завтра до 12:30\n"
        "- ТЕМА: обсуждение оставшихся купе и сметы на завтра\n"
    )
    items = b.items_from_facts(facts)
    check("форма 4 · решение в «Решения»", items["Решения"],
          ["отпустить Левона на клиентскую работу", "два плана оценки"])
    check("форма 4 · задача в «Задачи»", items["Задачи"],
          ["Оля посчитает итоговые цифры сегодня или завтра до 12:30"])
    check("форма 4 · вопрос остался один", items["Открытые вопросы"],
          ["оценка функционала для раздела декоративной косметики"])
    check("форма 4 · тема в «Ход обсуждения»", items["Ход обсуждения"],
          ["обсуждение оставшихся купе и сметы на завтра"])
    for section, texts in items.items():
        for text in texts:
            for label in b.FACT_LABELS:
                if label in text.upper():
                    FAILED.append(f"ярлык «{label}» уехал в конспект дословно: "
                                  f"[{section}] {text!r}")


def test_bold_label() -> None:
    """Форма 4-бис: тот же ярлык в болде — метка ищется после снятия разметки."""
