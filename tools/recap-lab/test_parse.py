# ---------------------------------------------------------------------------
# Слияние прозы: одна хронология, а не две
# ---------------------------------------------------------------------------

def test_prose_blocks_keep_bodies() -> None:
    """Строка без таймкода продолжает блок, а не становится своим абзацем."""
    lines = ["**Тема раз (05:14 – 12:13)**", "Тело первого абзаца.",
             "**14:57 – 20:34**: тело второго абзаца.", "*   подпункт второго"]
    check("блоки прозы", b.prose_blocks(lines),
          ["**Тема раз (05:14 – 12:13)**\nТело первого абзаца.",
           "**14:57 – 20:34**: тело второго абзаца.\n*   подпункт второго"])


def test_prose_single_chronology() -> None:
    """Две ветки дают одну хронологию: таймкоды не откатываются назад."""
    t0 = {b.NARRATIVE: ["**00:15 – 06:28**: начало", "**20:46 – 23:32**: смета"]}
    sample = {b.NARRATIVE: ["**Концепция (05:14 – 12:13)**", "Тело.",
                            "**26:57 – конец**: презентация"]}
    facts = {b.NARRATIVE: ["The act | декор. косметика"]}
    merged = b.merge_prose([t0, sample, facts])
    starts = [b.block_span(text)[0] for text in merged if b.block_span(text)]
    check("хронология не откатывается", starts, sorted(starts))
    # 2 блока t=0 + 2 блока сэмпла (тело приклеено к своему заголовку) + 1 без таймкода
    check("ничего не потеряно", len(merged), 5)
    check("блок без таймкода — в конце", merged[-1], "The act | декор. косметика")


