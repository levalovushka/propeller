#!/usr/bin/env bash
# Что на самом деле отдаёт система про вырез этого макбука.
#
# Нужен, потому что размеры выреза угадывать нельзя: они разные у 14″ и 16″,
# меняются вместе с выбранным разрешением, и вырез вдобавок стоит не по центру
# экрана. Один запуск на чужой машине — и строка для таблицы в `NotchGeometry`
# перестаёт быть догадкой.
#
#   ./run.sh
set -euo pipefail
cd "$(dirname "$0")"
out="$(mktemp -d)/notchprobe"
swiftc -O notchprobe.swift -o "$out"
"$out"
