import Foundation

/// Кто держит движок саммари включённым — и что из этого следует для таймера
/// простоя.
///
/// Таймер заводился ради одного: не держать 3,4 ГБ весов в памяти между
/// встречами. Но «простой» он понимал как «конвейер сейчас ничего не считает»,
/// а это не одно и то же: самая длинная работа движка — первая выдача модели,
/// и она идёт **вне** конвейера, десятками минут.
///
/// Чего это стоило. Человек, который записывает встречи (а он для этого
/// приложение и ставил), заканчивает любую фазу конвейера — расшифровку,
/// сохранение, чужое саммари; глубина работы обнуляется, заводится гашение
/// через 30 с. Через 30 с `ollama serve` получает SIGTERM **под живым пулом**,
/// стрим падает, лестница делает шаг. Блобы Ollama докачиваются, поэтому это
/// не «никогда», а «первая модель едет неделю» — ровно у тех, у кого встреч
/// больше всех. Замер за 30 дней: 8 человек, у которых локальная выдача
/// стартовала, ни разу не дошла до успеха и ни одного конспекта не появилось.
///
/// Отсюда две разные преграды, и обе нужны:
///
/// 1. **`mayArm`** — не заводить гашение, пока идёт попытка выдачи. Дешёвая,
///    но одной её мало: попытка начинается и после того, как таймер уже
///    заведён.
/// 2. **`whenTimerFires`** — дозвонивший таймер под работой не гасит, а
///    **переносится**. Тот же ответ, что у двойника на движке речи
///    (`SidecarLiveUse`, `GigasttSidecar.stopAfterIdle`): отмена оставила бы
///    модель в памяти до конца дня, а гашение оборвало бы работу.
///
/// Здесь, в `PropellerPure`, по обычной причине: `Sources/` — исполняемая цель,
/// до которой не дотягивается ни один тест, и ошибка в таком правиле не видна
/// месяцами — её видно только по тому, что у человека нет ни одного конспекта.
public struct EngineIdleStop: Equatable, Sendable {

    /// Сколько работ висит на движке прямо сейчас. Счётчик, а не флаг: выдача
    /// модели и генерация саммари могут перекрываться, и закрытие первой не
    /// повод гасить сервер под второй.
    public private(set) var users: Int

    public init(users: Int = 0) {
        self.users = max(0, users)
    }

    public mutating func begin() { users += 1 }

    /// Не уходит ниже нуля: закрытие зовут и `defer` попытки, и явная
    /// остановка, а лишний вычет открыл бы дорогу гашению под следующей
    /// работой.
    public mutating func end() { users = max(0, users - 1) }

    /// На движке кто-то работает прямо сейчас.
    public var isBusy: Bool { users > 0 }

    public enum Action: String, Equatable, Sendable {
        /// Никто не работает — модель обязана уйти из памяти.
        case stop
        /// Под работой не гасим, но и не забываем: тот же таймер заводится
        /// заново и дозвонит, когда работа кончится.
        case postpone
    }

    /// Что делает дозвонивший таймер простоя.
    public var whenTimerFires: Action { isBusy ? .postpone : .stop }

    /// Можно ли вообще заводить гашение сейчас.
    ///
    /// Отдельный вопрос с отдельным именем: тот, кто заводит таймер (конец
    /// фазы конвейера), про пул модели не знает ничего — он знает только, что
    /// **его** работа кончилась. Раньше он на этом основании и гасил.
    public static func mayArm(provisioningInFlight: Bool) -> Bool {
        !provisioningInFlight
    }
}
