import Foundation

/// # Что остаётся на диске от прошлой версии движка саммари
///
/// Движок распаковывается из тарбола в `Application Support/Meeting Recorder/ollama`
/// поверх того, что там уже лежит. Пока имена файлов совпадают, это ровно замена; но
/// половина имён версионированные — `libggml-base.0.17.0.dylib`, `libllama.0.0.1.dylib`, —
/// и после подъёма `releaseTag` они не перезаписываются, а просто перестают кому-то
/// принадлежать. Замерено 2026-08-21 на установленной 1.16.7: в каталоге 26 записей,
/// из них 13 несут номер версии в имени. Ни один из них никто не удаляет.
///
/// Правило описано здесь, а не в сайдкаре, по обычной причине: оно решает, что удалить
/// с чужого диска, и ошибиться может незаметно. Оно принимает два списка имён — что
/// лежит и что принёс новый тарбол, — и никогда не смотрит на файловую систему само.
///
/// Три вещи не удаляются никогда:
///
/// - `models/` — это 3,4 ГБ весов, скачанных по сети, и они не относятся к версии
///   движка. Удалить их значит устроить человеку повторную загрузку без спроса.
/// - `installed-version.txt` — наша собственная метка, её всё равно перепишут строкой ниже.
/// - `*.log` — единственное, что человек может прислать, когда саммари не собралось.
///
/// И самое важное: **пустой список от нового тарбола означает «ничего не удалять»**.
/// Не знать, что принёс архив, — это не то же самое, что знать, что он не принёс ничего;
/// второе прочтение вычистило бы каталог целиком.
public enum EngineHousekeeping {

    /// Имена, которые остаются в каталоге движка при любой замене версии.
    public static let alwaysKept: Set<String> = ["models", "installed-version.txt"]

    /// Что в каталоге движка осталось от прошлой версии.
    ///
    /// - Parameters:
    ///   - existing: имена верхнего уровня, лежащие в каталоге сейчас.
    ///   - shipped: имена верхнего уровня, которые принёс новый тарбол.
    public static func stalePaths(existing: [String], shipped: Set<String>) -> [String] {
        guard !shipped.isEmpty else { return [] }
        return existing.filter { name in
            guard !shipped.contains(name) else { return false }
            guard !alwaysKept.contains(name) else { return false }
            guard !name.hasSuffix(".log") else { return false }
            return true
        }.sorted()
    }

    /// Модели, которые мы когда-то выдавали дефолтом и больше не используем.
    ///
    /// Список хранится «что мы ставили», а не «что надо удалить»: второй способ уже
    /// стоил забытой строки — `supersededModels` знал только `qwen2.5:7b`, хотя дефолт
    /// с тех пор менялся. Забыть дописать историю тяжелее, чем забыть дописать
    /// исключение: без записи в истории модель не появилась бы у людей вообще.
    ///
    /// Область намеренно узкая — только теги, которые это приложение когда-то ставило
    /// само. `adopt-if-present` значит, что рядом может быть чужой Ollama, и удалять
    /// там произвольную модель нельзя (решение владельца 2026-07-27).
    public static func supersededModels(shippedDefaults: [String], current: String) -> [String] {
        var seen = Set<String>()
        return shippedDefaults.filter { tag in
            guard tag != current else { return false }
            return seen.insert(tag).inserted
        }
    }
}
