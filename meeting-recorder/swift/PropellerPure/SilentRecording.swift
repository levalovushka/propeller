import Foundation

/// # Запись, в которой никто не говорил
///
/// ASR дошёл до конца и не вернул ни слова. Это утверждение о **входе**, а не о
/// сервисе: та же попытка завтра даст тот же ноль, потому что в файле тишина.
/// Поэтому решение принимает вызывающая сторона, которая на этот вход смотрела,
/// а `PipelineRetry.classify` по-прежнему не имеет права вернуть `.terminal`.
///
/// Пока такого решения не было, пустая запись попадала в `transient` и вставала
/// на бесконечную лестницу: раз в час поднимался сайдкар на 981 МБ, тратил
/// секунду на те же двадцать секунд тишины, получал ноль токенов и парковался
/// снова — а строка всё это время шиммерила «В очереди» и обещала «Ждём ответа
/// сервиса» про сервис, который ответил за 0.7 с.
///
/// Дальше развилка ровно одна, и она про длительность:
///
/// - **Промах по кнопке.** Запись включили и тут же выключили. В ней нет ни
///   встречи, ни следа встречи — только пустой wav и строка в списке, которую
///   человеку придётся удалять руками. Такую запись приложение убирает само.
/// - **Настоящая тишина.** Двадцать минут, где все молчали: созвон, на который
///   никто не пришёл, забытый микрофон. Запись остаётся — она была, у неё есть
///   время, длительность и, возможно, календарное имя, — но выходит из очереди
///   и говорит человеческим языком, что говорить было некому.
public enum SilentRecording {

    /// Короче этого — промах по кнопке, а не встреча.
    ///
    /// Пять секунд, потому что это заведомо меньше любого «привет, слышно
    /// меня?»: даже самый короткий обмен репликами длиннее, а значит порог
    /// нельзя перешагнуть, сказав что-нибудь.
    public static let slipSeconds: TimeInterval = 5

    /// Что делать с записью, в которой не нашлось речи.
    public enum Verdict: Equatable, Sendable {
        /// Удалить целиком — вместе с аудио. Сохранять нечего, и строка в
        /// списке была бы единственным следом нажатой по ошибке кнопки.
        case discard
        /// Оставить в списке, вывести из очереди и сказать, почему.
        case rest
    }

    /// Приговор пустой записи.
    ///
    /// `hasTranscript` и `hasNotes` — не про тишину, а про то, что удалять
    /// нельзя: заметку человек написал руками, транскрипт остался от удачного
    /// прохода до того, как встречу отправили на переобработку. Пустой ответ
    /// ASR не повод стирать ни то, ни другое, какой бы короткой запись ни была.
    public static func verdict(
        duration: TimeInterval,
        hasTranscript: Bool,
        hasNotes: Bool
    ) -> Verdict {
        if hasTranscript || hasNotes { return .rest }
        return duration < slipSeconds ? .discard : .rest
    }
}
