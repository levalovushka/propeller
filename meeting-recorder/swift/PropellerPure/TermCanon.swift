import Foundation

/// Написание терминов в готовом конспекте.
///
/// Горячие слова чинят распознавание у источника, но чинят не всё: «онбординг»
/// лежит в `BuiltinHotwords` с самого начала, а в архиве автора встречается
/// «анбординг» — три раза из трёх. Дальше искажение живёт своей жизнью: модель
/// видит в транскрипте «майплайн» и добросовестно переписывает его в конспект,
/// потому что промпт запрещает ей выдумывать.
///
/// Отсюда второй рубеж — уже по тексту, который мы сами и написали. Правится
/// **только конспект**: транскрипт — данные пользователя, и переписывать
/// сказанное мы не вправе.
///
/// Таблицы собраны замером по 54 транскриптам (`tools/recap-lab`), и в них
/// попало лишь то, у чего **не встретилось ни одного правильного написания**:
///
/// | канон       | как звучит в архиве          |
/// |-------------|------------------------------|
/// | пайплайн    | майплайн ×3                  |
/// | дескриптор  | дискриптор ×7                |
/// | майндсет    | майнсет ×7                   |
/// | онбординг   | анбординг ×3                 |
/// | джоба       | джаба / джабы / джабов ×11   |
/// | бэклог      | беклог ×4                    |
/// | бэкенд      | бекенд ×3                    |
/// | Claude      | клод ×17, клоуд ×7           |
///
/// «Инстанция» (88 вхождений, ни одного «инстанс») сюда сознательно **не
/// попала**: это законное русское слово, и правило, которое чинит созвон,
/// сломает встречу, где говорили про суд или про инстанцию согласования.
/// Такие слова чинятся горячими словами, а не заменой постфактум.
public enum TermCanon {

    /// Искажённая основа → правильная основа. Хвост слова сохраняется, поэтому
    /// одна строка чинит все падежи: «джабов» → «джобов», «джабы» → «джобы».
    /// Порядок не важен — основы не пересекаются.
    static let stems: [(wrong: String, right: String)] = [
        ("майплайн", "пайплайн"),
        ("дискриптор", "дескриптор"),
        ("майнсет", "майндсет"),
        ("анбординг", "онбординг"),
        ("джаб", "джоб"),
        ("беклог", "бэклог"),
        ("бекенд", "бэкенд"),
        ("бэкэнд", "бэкенд"),
        ("фронтэнд", "фронтенд"),
        ("фронтент", "фронтенд"),
        // Добавлено 2026-08-08 замером **по конспектам**, а не по расшифровкам
        // (`vocab/mine.py --source recaps`). Разница существенная: горячие слова
        // правят распознавание, а эти поломки рождаются позже — модель пишет
        // «инстантов» там, где в расшифровке стояла «инстанция», и ни одно
        // горячее слово до этого места не достаёт.
        ("инстант", "инстанс"),        // 9 вхождений в конспектах, верного написания нет
        ("ритч-текст", "рич-текст"),   // 10 в расшифровках, оттуда переезжает в конспект
        // Добавлено 2026-08-15 замером по 20 последним встречам (`vocab/`, раздел
        // «Пополнение по 20 последним встречам»). Счёт — конспекты + расшифровки
        // по всему архиву; ни одна из основ слева не является русским словом,
        // поэтому замена не может задеть обычную речь.
        ("лондос", "лендос"),          // 7, верного написания в архиве нет вовсе
        ("лундос", "лендос"),          // 4, то же слово другим искажением
        ("реч-текст", "рич-текст"),    // 4, соседнее написание к «ритч-текст» выше
        ("мадборд", "мудборд"),        // 2, верного написания нет
        ("лок-шоп", "воркшоп"),        // 2
        ("классер", "кластер"),        // 2 (верно тоже: 161 — чиним написание, не слово)
        ("сториеллинг", "сторителлинг"), // 1
        ("вейпкод", "вайбкод"),        // 1
    ]

    /// Основа → название целиком. Названия продуктов на письме не склоняются,
    /// поэтому «клода» становится «Claude», а не «Claudeа»: падежный хвост
    /// отбрасывается вместе с основой.
    static let names: [(wrong: String, right: String)] = [
        ("клод", "Claude"),
        ("клоуд", "Claude"),
        ("кложд", "Claude"),
        // Storybook в конспектах звучит четырьмя способами и ни разу — своим.
        // В расшифровках это «стурибук» и «стрибук», в конспектах модель
        // достраивает их до «стейтбука», подтягивая знакомое слово «стейт».
        ("стейтбук", "Storybook"),
        ("стрибук", "Storybook"),
        ("стурибук", "Storybook"),
        ("сторибук", "Storybook"),
    ]

    /// Сколько букв разрешено отбросить как падежное окончание. «клодик» — да,
    /// пять букв хвоста — уже другое слово, и заменять его нельзя.
    private static let maxInflection = 3

    /// Канонизировать написание терминов в тексте конспекта.
    ///
    /// Регистр первой буквы сохраняется: «Майплайн» в начале пункта останется
    /// «Пайплайн», иначе замена ломала бы предложение сильнее, чем опечатка.
    public static func normalize(_ text: String) -> String {
        var result = ""
        result.reserveCapacity(text.count)
        var word = ""

        func flush() {
            guard !word.isEmpty else { return }
            result += canonical(word)
            word = ""
        }

        for character in text {
            if character.isLetter || character == "-" {
                word.append(character)
            } else {
                flush()
                result.append(character)
            }
        }
        flush()
        return result
    }

    // MARK: -

    private static func canonical(_ word: String) -> String {
        let lower = word.lowercased()

        for name in names where lower.hasPrefix(name.wrong)
            && lower.count - name.wrong.count <= maxInflection {
            return name.right
        }
        for stem in stems where lower.hasPrefix(stem.wrong) {
            let tail = String(word.dropFirst(stem.wrong.count))
            let fixed = stem.right + tail
            return word.first?.isUppercase == true ? capitalizedFirst(fixed) : fixed
        }
        return word
    }

    private static func capitalizedFirst(_ text: String) -> String {
        guard let first = text.first else { return text }
        return first.uppercased() + text.dropFirst()
    }
}
