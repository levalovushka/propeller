import Foundation

/// # Можно ли сейчас опубликовать саммари
///
/// Правило до нажатия, а не оправдание после. Владелец 2026-08-27: «лучше
/// понять, какая ошибка может быть, и предотвратить» — поэтому то, что видно
/// заранее, гасит кнопку и объясняет причину, а строка ошибки остаётся только
/// для того, что заранее не увидишь.
///
/// Чего здесь **нет** и почему:
///
/// - **Размера.** Сервер принимает 2 МиБ (`server/share/main.go`), а блоб
///   перед отправкой сжимается (`ShareCrypto.seal` → `deflate`). Саммари,
///   которое после сжатия не влезет в два мегабайта, — это несколько
///   мегабайт текста; такой встречи не бывает. Проверка была бы кодом,
///   который не может сработать.
/// - **Отсутствия ключа публикации.** `ShareService.isAvailable` умеет быть
///   ложным, но по решению владельца это не состояние интерфейса, а дефект
///   сборки: «надо сделать так, чтобы такое стечение обстоятельств было
///   невозможным». Рисовать для него экран значило бы узаконить.
public enum SharePlateState {

    /// Почему кнопка публикации не нажимается.
    public enum Obstacle: Equatable, Sendable {
        /// Сети нет. Единственная причина, которую видно заранее и которая
        /// проходит сама.
        case offline
        /// Публиковать нечего: саммари ещё не собрано.
        case nothing

        /// Что написано под кнопкой. Копирайт в одном месте
        /// (`design/principles.md` §6): и модалка, и тест читают эту строку.
        public var reason: String {
            switch self {
            case .offline: return "Без интернета не получится"
            case .nothing: return "Саммари ещё нет — делиться нечем"
            }
        }
    }

    /// `nil` — публиковать можно.
    ///
    /// Порядок именно такой: «нечего публиковать» важнее «нет сети». Сеть
    /// появится сама, а пустое саммари от неё не наполнится, и сказать про
    /// интернет там, где дело не в нём, — соврать.
    public static func obstacle(hasSummary: Bool, isOnline: Bool) -> Obstacle? {
        if !hasSummary { return .nothing }
        if !isOnline { return .offline }
        return nil
    }
}
