import Foundation

/// # Когда имя встречи берёт клавиатуру
///
/// Имя — это поле ввода, и любая буква в нём переименовывает встречу. Поэтому
/// фокус оно принимает только тогда, когда его попросил человек: мышью, над
/// самим именем.
///
/// Иначе фокус ему раздаёт сам AppKit. Окно, встающее на экран, ищет первый вид
/// в цепочке клавиатуры (`_setUpFirstResponder` → `_selectFirstKeyView`), и на
/// экране идущей записи им оказывалось поле имени: замерено 2026-11-05
/// стеком `makeFirstResponder` в экспорте галереи, на всех кадрах записи, в том
/// числе до переезда имени из полосы в тело. Окно, открытое посреди встречи,
/// встречало человека выделенным именем, и первая нажатая буква его стирала.
public enum TitleFocusPolicy {

    /// Оставить ли фокус, который поле имени только что получило.
    ///
    /// - Parameters:
    ///   - pointerOverName: курсор над именем — так выглядит щелчок по нему.
    ///   - mouseDown: фокус пришёл из нажатия кнопки мыши.
    public static func keeps(pointerOverName: Bool, mouseDown: Bool) -> Bool {
        pointerOverName || mouseDown
    }
}
