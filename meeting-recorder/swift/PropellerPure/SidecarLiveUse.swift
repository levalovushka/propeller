import Foundation

/// Сколько живых сессий висит на движке речи — и что из этого следует.
///
/// Счётчик заводился ради одного: не перезапускать сервер ради нового словаря
/// встречи под открытой лентой. Но у сервера есть второй способ умереть —
/// остановка по простою, — и её спрашивали не здесь, а нигде: `stopAfterIdle`
/// про живые сессии не знал.
///
/// Чего это стоило. Встреча А кончилась, пошёл догон ASR на минуты; началась
/// встреча Б, воркера сняли, догон упал по отмене — и его `defer` всё равно
/// поставил остановку по простою. Через 45 секунд встречи Б сайдкару прилетал
/// SIGTERM, лента живого текста обрывалась на полуслове, а лестница
/// переподключения поднимала сокет в мёртвый порт до конца звонка. Человек
/// видел 45 секунд живого текста и тишину дальше — ни строки, ни значка.
///
/// Здесь, в `PropellerPure`, потому что `Sources/` — исполняемая цель, которую
/// не импортирует ни один тест, а это ровно то правило, ошибку в котором никто
/// не замечает месяц.
public struct SidecarLiveUse: Equatable, Sendable {

    /// Открытых пар сессий (микрофон + система считаются одной: слушатель один).
    public private(set) var users: Int

    public init(users: Int = 0) {
        self.users = max(0, users)
    }

    public mutating func begin() { users += 1 }

    /// Не уходит ниже нуля: закрытие зовут и `stop()`, и `end()`, и лишний
    /// вычет открыл бы дорогу остановке под живой лентой.
    public mutating func end() { users = max(0, users - 1) }

    /// Кто-то слушает прямо сейчас.
    public var isBusy: Bool { users > 0 }

    /// Можно ли перезапустить сервер ради сменившегося словаря встречи.
    /// Потерянная подсказка дешевле оборванной встречи.
    public var mayRestartForTerms: Bool { !isBusy }

    /// Можно ли гасить сервер, когда дозвонил таймер простоя.
    ///
    /// Отдельное имя, а не `!isBusy` на месте вызова: это два разных вопроса с
    /// одним ответом сегодня, и «почему нельзя» у них разное.
    public var mayStopOnIdle: Bool { !isBusy }
}
