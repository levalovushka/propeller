import Foundation

/// Чем питается лопасть в чёлке: звук, который в этот момент пишется.
///
/// Это единственный прибор записи, который мы показываем, и он отвечает сразу
/// на три вопроса — идёт ли запись, доходит ли до нас звук и не стоим ли мы на
/// паузе. Таймера рядом нет намеренно: секунды тикают и при мёртвом микрофоне,
/// а лопасть — нет.
///
/// Три вещи, на которых всё держится, и каждая проверяется тестом:
///
/// 1. **Инерция большая.** Лопасть отражает «в комнате идёт разговор», а не
///    отдельный слог. Реагируй она на фонему — у камеры собеседника оказался бы
///    стробоскоп.
/// 2. **В тишине лопасть не встаёт**, а идёт холостым ходом. Тишина в записи —
///    это норма (человек слушает), и остановка в ней читалась бы как поломка.
/// 3. **Ноль — это только пауза.** Полная неподвижность освобождена под одно
///    состояние, поэтому её нельзя ни с чем спутать через всю комнату.
public enum BladeDrive {

    /// Холостой ход: оборот почти за полминуты. Движение, которое замечаешь,
    /// только если посмотреть на него дважды.
    public static let idleSpeed: Double = -14

    /// Полная мощность — оборот за секунду с небольшим. Размах между этим и
    /// холостым ходом и есть весь прибор: на первой версии (36…180) разгон в
    /// разговоре читался «еле-еле», и шкала была расширена в обе стороны.
    public static let topSpeed: Double = -420

    /// Ниже этого пика в комнате тишина. Замерено по дорожкам: собственный шум
    /// тракта живёт под 0.02.
    public static let floorLevel: Float = 0.02

    /// Отсюда лопасть уже на полной мощности. Речь в метре от микрофона даёт
    /// пики 0.1–0.5, и «громче» после этого места ничего не меняет.
    public static let ceilingLevel: Float = 0.5

    /// Насколько быстро приходит мощность: 63 % за это время.
    public static let attack: Double = 1.0

    /// Насколько долго уходит. Втрое дольше, чем приходит: это выбег, а не
    /// затухание сигнала — фраза кончилась, лопасть ещё идёт.
    public static let release: Double = 3.0

    /// Выбег до нуля при паузе. Короткий: пауза — это решение человека, и она
    /// должна дочитываться раньше, чем он успеет усомниться, что нажал. С
    /// порогом остановки ниже это даёт полную неподвижность за ~0,9 с даже с
    /// полной мощности.
    public static let pauseRelease: Double = 0.35

    /// Ниже этого лопасть на паузе объявляется остановленной. Порог отдельный
    /// от холостого хода: холостой ход медленный намеренно, и ждать, пока
    /// экспонента доедет до него, значит секунду врать про то, пишем мы или нет.
    public static let stopThreshold: Double = 30

    /// Как быстро огибающая догоняет пришедший пик.
    ///
    /// Быстро, но не мгновенно: начало фразы должно подхватываться, отдельный
    /// щелчок — нет.
    public static let envelopeAttack: Double = 0.12

    /// Как долго она держится, когда пики перестали приходить. Длиннее любой
    /// паузы между словами и короче паузы между репликами: первую лопасть не
    /// должна замечать, вторую — должна.
    public static let envelopeRelease: Double = 0.7

    /// Огибающая уровня — то, чем на самом деле питается лопасть.
    ///
    /// Приходящее из захвата — это **пик за буфер**, самая шумная мера
    /// громкости из возможных, и приходит он редко (раз в несколько десятков
    /// миллисекунд). Кормить приводом прямо им нельзя: `timeConstant` тянет
    /// вверх втрое быстрее, чем отпускает, и на чередовании «слог — пауза
    /// между словами» это работает храповиком — толчок на каждом пике,
    /// медленное сползание между ними. Именно так лопасть и дёргалась на
    /// громком звуке из динамиков, где размах пиков наибольший.
    ///
    /// Огибающая снимает рывки до того, как они станут скоростью: асимметрия
    /// привода после неё описывает фразу, ради чего и заводилась, а не слог.
    public static func envelope(_ current: Float, level: Float, dt: Double) -> Float {
        guard dt > 0 else { return current }
        let level = max(0, min(1, level))
        let tau = level > current ? envelopeAttack : envelopeRelease
        let k = Float(exp(-dt / tau))
        return level + (current - level) * k
    }

    /// Мощность 0…1 по огибающей дорожки.
    ///
    /// Шкала логарифмическая, потому что амплитуда — нет: на линейной обычная
    /// речь всю встречу простояла бы у самого пола.
    public static func power(level: Float) -> Double {
        let level = Double(max(0, min(1, level)))
        let floor = Double(floorLevel), ceiling = Double(ceilingLevel)
        guard level > floor else { return 0 }
        guard level < ceiling else { return 1 }
        return (log10(level) - log10(floor)) / (log10(ceiling) - log10(floor))
    }

    /// Скорость, к которой лопасть идёт прямо сейчас, °/с.
    public static func targetSpeed(level: Float, paused: Bool) -> Double {
        guard !paused else { return 0 }
        return idleSpeed + (topSpeed - idleSpeed) * power(level: level)
    }

    /// Сколько времени лопасть тратит на то, чтобы дойти до цели.
    public static func timeConstant(from current: Double, to target: Double, paused: Bool) -> Double {
        if paused { return pauseRelease }
        // Быстрее — это мощность, медленнее — выбег. Знак у скоростей
        // отрицательный (лопасть идёт против часовой), поэтому сравниваем модули.
        return abs(target) > abs(current) ? attack : release
    }

    /// Шаг интегрирования: экспоненциальное приближение к цели за `dt`.
    ///
    /// Кадр может опоздать (система занята, экран проснулся) — и приближение по
    /// `exp(-dt/τ)` этого не замечает: результат зависит от прошедшего времени,
    /// а не от числа кадров.
    /// `level` здесь — уже огибающая (`envelope`), а не пик из захвата.
    public static func advance(
        speed: Double,
        level: Float,
        paused: Bool,
        dt: Double
    ) -> Double {
        guard dt > 0 else { return speed }
        let target = targetSpeed(level: level, paused: paused)
        let tau = timeConstant(from: speed, to: target, paused: paused)
        let next = target + (speed - target) * exp(-dt / tau)
        // На паузе лопасть обязана встать совсем, и раньше, чем экспонента
        // дойдёт до нуля сама: всё, что медленнее холостого хода, — это уже не
        // «идёт запись», а неотличимое от остановки ползание. Досидеть в нём
        // три секунды значит три секунды врать про то, пишем мы или нет.
        if paused, abs(next) < stopThreshold { return 0 }
        return next
    }
}
