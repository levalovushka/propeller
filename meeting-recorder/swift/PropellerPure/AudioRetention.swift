import Foundation

/// # Сколько живёт аудио
///
/// Аудио — самое тяжёлое, что есть у встречи, и единственное, что она умеет
/// потерять без потери смысла. Кто именно умеет — уже решено и проверено
/// (`AudioReclaim`); здесь решается только **когда**, и это правило не имеет
/// права ответить «можно» там, где то отвечает «нельзя»: иначе появилась бы
/// вторая истина о том, кому ещё нужен звук.
///
/// ## Два режима, и третьего нет
///
/// Решение владельца 2026-08-20: либо звук уходит сразу после расшифровки, либо
/// лежит **ровно** тридцать дней. Ни «хранить всегда», ни выбора числа дней:
/// оба существовали для случая, который никто не назвал, а настройка, которой
/// не пользуются, — это ещё один способ получить архив, ведущий себя иначе, чем
/// думает владелец. Дефолт — `afterTranscript`, и довод у него короткий:
/// **слушать записи приложение не даёт и не планирует**, а в то, что человек
/// пойдёт искать wav на диске и откроет его сам, верить нельзя.
///
/// Плеер (`AudioPlayer`, `WaveformScrubber`) удалён тем же решением 2026-08-18:
/// он висел без двери и делал вид, что слушание когда-нибудь появится.
///
/// **Что этим сознательно отдано.** Переразбор архива движком получше, повторная
/// диаризация слипшегося `Speaker S1` и паралингвистика (§3.2 вижена: «голос
/// выше на треть, два перебивания») считаются из звука. После расшифровки его
/// нет — значит всё это будет доступно только встречам, записанным после того,
/// как такая работа появится, и только у того, кто выбрал тридцать дней.
/// Доводы предъявлены и отклонены; это цена, а не недосмотр.
public enum AudioRetentionMode: String, Codable, CaseIterable, Identifiable, Sendable {
    /// Как только звук перестал быть входом фазы — то есть сразу после успешной
    /// расшифровки и диаризации.
    case afterTranscript
    /// Через `AudioRetention.defaultDays` после встречи, и только если звук уже
    /// не вход.
    case afterDays

    public var id: String { rawValue }

    /// Что говорит сегментед. Рядом с кейсами, чтобы новый режим не мог
    /// приехать без слова для него.
    ///
    /// Оба пункта — ответы на вопрос из заголовка строки («хранить аудио — до
    /// расшифровки / 30 дней»): одна грамматическая форма, по два слова на
    /// сторону. Сегментед из длинных подписей — колбаса, а не выбор.
    public var displayName: String {
        switch self {
        case .afterTranscript: return "До расшифровки"
        case .afterDays:       return "30 дней"
        }
    }
}

public enum AudioRetention {

    /// Тридцать дней, и это число, а не настройка (решение владельца
    /// 2026-08-20). Месяц — срок, за который к записи возвращаются: спорная
    /// формулировка в конспекте проверяется по звуку на следующей встрече серии,
    /// а серии здесь недельные и двухнедельные. Меньше — и проверять станет
    /// нечем; больше — и режим перестаёт что-либо освобождать. Выбор числа был
    /// и убран: степпер спрашивал то, на что человеку нечем ответить.
    public static let days = 30

    /// Что делать с тем, что уже записано в настройках.
    ///
    /// Дефолт применяется только там, где ключа нет, — значит смена дефолта не
    /// доходит до того, у кого значение записано. За два дня режим успел
    /// побывать `keep`, `afterDays` и `afterTranscript` (17–18 августа), плюс
    /// `keep` и выбор числа дней теперь удалены совсем. У всех, кто в те дни
    /// трогал пикер, в defaults лежит ответ на вопрос, которого больше нет.
    ///
    /// Поэтому сброс, а не разбор: retention нигде не выпущен (1.16.5 — 16
    /// августа, режим родился 17-го), так что записанное — это шум dogfood-окна,
    /// а не чей-то выбор. Один раз стереть и жить по нынешнему дефолту честнее,
    /// чем угадывать, что человек имел в виду тремя режимами назад.
    public enum StoredMode: Equatable, Sendable {
        /// Записанному верят.
        case use(AudioRetentionMode)
        /// Записанное **стирают** из defaults, а не просто игнорируют на
        /// чтении: сегментед держит не `Preferences`, а строку из defaults
        /// напрямую (`@AppStorage`), и оставленное там значение продолжило бы
        /// показывать человеку не то, по чему живёт приложение, — а незнакомое
        /// ему значение и вовсе не выбрало бы ни одного пункта из двух.
        case reset(AudioRetentionMode)
    }

    /// - Parameters:
    ///   - raw: что лежит по ключу `audioRetentionMode`, `nil` — если ничего.
    ///   - resetDone: сброс уже делали. Флаг односторонний и одноразовый: без
    ///     него сброс повторялся бы каждый запуск и стирал бы выбор человека.
    public static func storedMode(raw: String?, resetDone: Bool) -> StoredMode {
        guard resetDone else { return .reset(.afterTranscript) }
        // Ключа нет — человек ничего не выбирал, дефолт применится сам.
        // Запись здесь превратила бы дефолт в выбор, и следующая его смена
        // так же молча прошла бы мимо.
        guard let raw, !raw.isEmpty else { return .use(.afterTranscript) }
        guard let mode = AudioRetentionMode(rawValue: raw) else {
            return .reset(.afterTranscript)
        }
        return .use(mode)
    }

    /// Встреча глазами retention: всё, что нужно решению, и ничего больше.
    public struct Candidate: Equatable, Sendable {
        public let id: String
        public let date: Date
        public let stage: RecordingStage
        public let hasTranscript: Bool
        /// Есть ли ещё что удалять. Правило не должно называть «истёкшими»
        /// встречи, у которых звука и так нет, — иначе счётчик «освободили у N
        /// встреч» врёт каждый раз.
        public let hasAudio: Bool

        public init(
            id: String, date: Date, stage: RecordingStage,
            hasTranscript: Bool, hasAudio: Bool
        ) {
            self.id = id
            self.date = date
            self.stage = stage
            self.hasTranscript = hasTranscript
            self.hasAudio = hasAudio
        }
    }

    /// У кого пора забрать звук.
    ///
    /// - Parameter now: время решения, входом — чтобы срок проверялся тестом, а
    ///   не ожиданием тридцати дней.
    public static func expired(
        _ candidates: [Candidate],
        mode: AudioRetentionMode,
        now: Date = Date()
    ) -> [String] {
        let limit = TimeInterval(days) * 86_400
        return candidates.filter { candidate in
            guard candidate.hasAudio else { return false }
            // Единственная истина о том, кому ещё нужен звук.
            guard AudioReclaim.isExpendable(
                stage: candidate.stage, hasTranscript: candidate.hasTranscript
            ) else { return false }
            switch mode {
            case .afterTranscript:
                return true
            case .afterDays:
                // `>=`, а не `>`: срок «через 30 дней» истекает в момент, когда
                // прошло тридцать, а не когда пошёл тридцать первый.
                return now.timeIntervalSince(candidate.date) >= limit
            }
        }.map(\.id)
    }
}
