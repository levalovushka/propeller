import Foundation

/// Во что целиться при захвате системного звука.
///
/// # Почему это отдельное решение
///
/// Раньше ответ был зашит двумя способами сразу: константа `["us.zoom.xos"]` в
/// захвате и таблица платформ в детекторе. Из-за этого Контур.Толк, который
/// детектор прекрасно знает, для захвата не существовал — его звонки писались
/// целиком с машины. Один вопрос, два ответа, и один из них строка в коде.
///
/// # Почему «весь экран» — это не запасной вариант
///
/// Раньше захват молча переключался на весь экран, если за четыре секунды не
/// услышал ничего громкого. Это описывает нормальное начало почти любой встречи,
/// а цена — подмена смысла записи: вместо звонка пишется машина, вместе с
/// музыкой и уведомлениями. Живой звонок 2026-07-29 показал, что компенсировать
/// там нечего: app-scoped фильтр отдаёт звук звонка вместе с хелперами
/// (`docs/AUDIO-CAPTURE-CASES.md`).
///
/// Поэтому весь экран остаётся ровно для одного честного случая: **ни одного
/// знакомого приложения не запущено**, а человек всё равно нажал «записать».
public enum CaptureScope: Equatable {
    /// Пишем звук этих приложений (bundle id в том виде, в каком их вернула
    /// система — сравнение регистронезависимое, а подставлять надо оригинал).
    case applications([String])
    /// Ничего знакомого не запущено — пишем то, что играет машина.
    case wholeMachine
}

public enum CaptureScopePolicy {

    /// `runningBundleIDs` — то, что система показала как запущенное; порядок
    /// сохраняется, чтобы результат был предсказуем в логах и тестах.
    public static func scope(
        runningBundleIDs: [String],
        platforms: [MeetingPlatform] = MeetingPlatform.all
    ) -> CaptureScope {
        let known = Set(platforms.flatMap(\.bundleIDs))
        let matched = runningBundleIDs.filter { known.contains($0.lowercased()) }
        return matched.isEmpty ? .wholeMachine : .applications(matched)
    }
}
