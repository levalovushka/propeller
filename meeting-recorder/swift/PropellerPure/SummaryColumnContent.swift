import Foundation

/// # Что стоит на месте саммари, пока саммари нет
///
/// У встречи есть глубина, и колонка показывает самое глубокое из того, что уже
/// есть: саммари, если оно готово; иначе расшифровку, если саммари ещё будет;
/// и только когда дальше ничего не будет — строку о том, почему.
///
/// Правило именно такое из-за минуты между «расшифровали» и «суммировали».
/// Раньше в эту минуту колонка говорила «Саммари пока нет» поверх текста,
/// который человек в этот момент читал: приложение отбирало готовое, чтобы
/// сообщить об отсутствии недоделанного.
///
/// Живёт в `PropellerPure`, потому что это правило, а не отрисовка.
public enum SummaryColumnContent: Equatable, Sendable {
    /// Саммари готово — оно и есть колонка.
    case summary
    /// Саммари ещё будет; до тех пор читают то, что уже расшифровано.
    case transcript
    /// Показывать нечего, и вот почему (`MeetingRest.disclosure`).
    case nothing(String)

    /// Ничего не готово и причины нет: встреча только начала свой путь.
    public static let defaultNothing = "Саммари пока нет"

    public static func decide(
        hasSummary: Bool,
        hasTranscript: Bool,
        rest: MeetingRest
    ) -> SummaryColumnContent {
        if hasSummary { return .summary }
        // Ждём следующую ступень — читают предыдущую. Всегда, а не только когда
        // сказать нечего.
        //
        // Раньше здесь была развилка по `disclosure`: если ожидание длинное и у
        // него есть имя («докачается модель», «ждём сервиса»), колонка называла
        // его вместо расшифровки. Это ошибка того же рода, что и починенная до
        // неё, только на ступень выше: приложение снова отбирало готовый текст,
        // чтобы сообщить о недоделанном. Причём чем длиннее ожидание, тем
        // дороже обходился обмен — «докачается модель» может стоять час, и весь
        // этот час человек не видит того, что уже расшифровано.
        //
        // Что идёт обработка, говорит рельс: у встречи шиммер и строка фазы
        // (`SidebarRowState.preview`). Это его работа — сказать, что происходит;
        // работа колонки — показать самое глубокое из того, что уже есть.
        //
        // Без оговорки про «ждём ли ещё чего-нибудь», и это разбиралось
        // отдельно. Единственное, что такая оговорка меняла, — доведённая
        // встреча, у которой файла саммари нет: с ней колонка говорила «Саммари
        // пока нет» вместо расшифровки. Но такого состояния не бывает — а если
        // случится, чинить его должна не колонка. `.summarized` ⟺ файл и
        // метаданные на месте (I9), `reconcileSummarizedStage` сверяет это в обе
        // стороны, откатывает стадию на `.saved` — и бэкфилл дописывает саммари
        // сам. Причина остановки при этом не теряется: у встречи, в которой не
        // нашлось речи, расшифровки нет по определению (каждое место, ставящее
        // `.noSpeech`, требует пустой расшифровки), поэтому «Никто ничего не
        // сказал» приходит следующей строкой.
        if hasTranscript { return .transcript }
        // Расшифровки нет. Вот тут строка — всё, что колонка может дать.
        return .nothing(rest.disclosure ?? defaultNothing)
    }
}
