import Foundation

/// Сборка транскрипта из двух дорожек, снятых по одним часам.
///
/// # Зачем
///
/// Диаризация по миксу не держит границу говорящего. Это видно глазами в
/// расшифровке, присланной тестировщиком: одна строка, один подписанный автор, а
/// говорили двое —
///
///     Speaker S1  06:46
///     — Угу. — Мне пон прикол… — Да, хорошо.
///
/// — и рядом фраза одного человека, разрезанная пополам между двумя спикерами.
/// Конспект поверх такого текста связывает решения не с теми людьми.
///
/// **Насколько это часто — не измерено.** Первая попытка дала 68–87 % и
/// оказалась негодной: та же формула на ленте, собранной здесь, показывает
/// 96–99 % (см. `mixedLines` ниже). Слова при этом не теряются — покрытие микса
/// 89–95 %, замерено надёжно, — ломается именно принадлежность. Этот файл
/// написан по дефекту, который виден, но чей размер ещё предстоит померить
/// честной метрикой.
///
/// # Почему это решается склейкой, а не лучшей диаризацией
///
/// Микрофонный стем снят до колонки: всё, что в нём осталось после `EchoDedup`,
/// произнёс владелец. Это не оценка и не порог — это свойство записи. Значит
/// одну границу из двух можно не угадывать, а знать, и диаризации остаётся
/// только дальняя сторона, где владельца нет вовсе.
///
/// # Что здесь есть и чего нет
///
/// Реплики разных говорящих **никогда** не сливаются — ради этого всё и
/// затевалось. Соседние реплики одного человека, наоборот, сливаются, если между
/// ними меньше `pauseSeconds`: ASR режет речь по дыханию, и без склейки лента
/// рассыпается на обрывки в три слова.
///
/// Одновременная речь остаётся двумя строками, а не одной: они и были двумя
/// репликами. Порядок — по началу, потому что читают ленту сверху вниз.
public enum StemMerge {

    /// Пауза, после которой соседние реплики одного человека — уже разные
    /// реплики. Меньше — лента рассыпается на обрывки, больше — в одну строку
    /// уезжает то, что человек сказал до и после чужого ответа.
    public static let pauseSeconds: Double = 1.5

    public struct Line: Equatable, Sendable {
        public let start: Double
        public let end: Double
        public let speaker: String
        public let text: String

        public init(start: Double, end: Double, speaker: String, text: String) {
            self.start = start
            self.end = end
            self.speaker = speaker
            self.text = text
        }
    }

    /// Собрать ленту из речи владельца и всех остальных.
    ///
    /// - Parameters:
    ///   - owner: микрофонная дорожка после снятия эха — по построению владелец.
    ///   - others: системная дорожка, где спикеров уже расставила диаризация.
    public static func merge(owner: [Line], others: [Line]) -> [Line] {
        let all = (owner + others)
            .filter { !$0.text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty }
            .sorted { ($0.start, $0.end) < ($1.start, $1.end) }

        var out: [Line] = []
        for line in all {
            // Слить можно только с предыдущей репликой того же человека, только
            // если между ними пауза — и только если в эту паузу никто не
            // заговорил. Иначе длинная склеенная строка накрывает чужой ответ по
            // времени, и лента перестаёт передавать порядок разговора: текст в
            // ней чужой не содержит, а прочитать, кто кому ответил, уже нельзя.
            if let last = out.last,
               last.speaker == line.speaker,
               line.start - last.end <= pauseSeconds,
               !all.contains(where: {
                   $0.speaker != line.speaker && $0.end > last.end && $0.start < line.start
               }) {
                out[out.count - 1] = Line(
                    start: last.start,
                    end: max(last.end, line.end),
                    speaker: last.speaker,
                    text: last.text + " " + line.text
                )
            } else {
                out.append(line)
            }
        }
        return out
    }

    /// Сколько реплик по времени накрывают речь более чем одного человека.
    ///
    /// **Осторожно: как мера путаницы говорящих это не работает.** Проверено на
    /// четырёх встречах: на ленте, собранной здесь — где текст каждой строки по
    /// построению принадлежит одному человеку, — величина даёт 96–99 %. Куски
    /// ASR обеих дорожек покрывают почти всё время встречи, включая паузы и
    /// дыхание, поэтому «в окно строки попал кто-то ещё» верно почти всегда.
    ///
    /// Числа 68–87 %, которыми был обоснован этот файл, получены той же
    /// формулой и потому не значат того, что им приписали. Мера принадлежности
    /// должна сравнивать **текст** строки с текстом дорожек, а не времена;
    /// пока такой меры нет, выигрыш склейки не измерен.
    ///
    /// Оставлено как есть, с этой оговоркой: величина честно показывает
    /// плотность перекрытия дорожек и пригодится, когда появится настоящая
    /// метрика — но выводов о говорящих из неё делать нельзя.
    public static func mixedLines(_ lines: [Line], against sources: [Line]) -> Int {
        lines.reduce(into: 0) { count, line in
            let speakers = Set(
                sources
                    .filter { $0.end > line.start && $0.start < line.end }
                    .map(\.speaker)
            )
            if speakers.count > 1 { count += 1 }
        }
    }
}
