import Foundation

/// Приведение путей из настроек к пригодному виду.
///
/// # Откуда это взялось
///
/// Поля путей в настройках — обычные текстовые поля. Один невидимый символ в
/// конце уводит приложение в **соседний каталог**: `recordings ` с хвостовым
/// пробелом — это не `recordings`. Приложение создаёт его, показывает пустой
/// список, и человек видит, что все его встречи пропали.
///
/// Так и случилось 2026-07-29. Архив был цел до последнего файла: 13 записей,
/// 42 файла стемов, 30 заметок — всё на месте. Стоил этот пробел нескольких
/// очень неприятных минут владельцу, потому что «пусто» и «потеряно» с той
/// стороны экрана выглядят одинаково.
public enum ArchivePath {

    /// Путь, каким его можно отдавать файловой системе.
    ///
    /// Обрезка нужна **на чтении**, а не только на записи: испорченные
    /// настройки уже лежат у людей на дисках, и починиться они должны сами, от
    /// обновления, а не от того, что кто-то догадается открыть настройки и
    /// подчистить хвост.
    ///
    /// Пустая строка после обрезки — это не путь, а стёртое поле: без запасного
    /// значения запись пошла бы в корень.
    public static func normalized(_ raw: String?, default fallback: String) -> String {
        let trimmed = (raw ?? "").trimmingCharacters(in: .whitespacesAndNewlines)
        return trimmed.isEmpty ? fallback : trimmed
    }
}
