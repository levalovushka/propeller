import Foundation

/// # Чей это файл на диске
///
/// В папке записей лежит wav, которого нет в индексе. Значений у этого ровно
/// два, и на диске они выглядят **одинаково**:
///
/// - мы её потеряли — индекс не дописался, процесс убили между записью файла и
///   записью индекса, — и тогда встречу надо подобрать, иначе человек её просто
///   не увидит;
/// - её удалил человек — и тогда подобрать её значит вернуть в список то, что
///   он выбросил, без названия и без заметок, и заставить его удалять дважды.
///
/// Пока различия не было, побеждало первое: `scanForOrphanRecordings`
/// усыновлял всё подряд. Удаление переживало обычный выход (`commitPendingDeletion`
/// в `applicationWillTerminate` успевал стереть аудио), но не переживало
/// `SIGKILL` и падение — а именно там человек и не нажимает ничего сам.
///
/// Надгробие — это и есть недостающее различие: запись о том, что удаление
/// было, живущая на диске отдельно от индекса, потому что индекса к этому
/// моменту у встречи уже нет.
public struct MeetingTombstone: Codable, Equatable, Sendable {
    public let id: String
    public let at: Date

    public init(id: String, at: Date) {
        self.id = id
        self.at = at
    }
}

public enum OrphanAdoption {

    /// Какие файлы на диске надо завести в индексе.
    ///
    /// Порядок проверок — всё содержание функции: сначала «мы её уже знаем»
    /// (дёшево и снимает подавляющее большинство), потом «её удалили». Надгробие
    /// стоит последним намеренно: запись, которая **есть** в индексе, важнее
    /// любого надгробия — значит удаление отменили через ⌘Z, а надгробие просто
    /// не успели убрать.
    public static func adoptable(
        fileIDs: [String],
        knownIDs: Set<String>,
        tombstoned: Set<String>
    ) -> [String] {
        fileIDs.filter { !knownIDs.contains($0) && !tombstoned.contains($0) }
    }

    /// Надгробия, которые ещё нужны.
    ///
    /// Надгробие сторожит ровно один файл. Нет файла — усыновлять нечего, и
    /// сторожить нечего: камень уходит. Без этого правила файл был бы вечным —
    /// монотонно растущий список всего, что человек когда-либо удалил.
    ///
    /// Именно поэтому надгробие не удаляется в момент, когда стирается аудио:
    /// стирание может не удаться (том отмонтирован, файл занят), и тогда камень
    /// обязан остаться. Он уйдёт сам на первом же скане, где файла правда нет.
    public static func pruned(
        _ stones: [MeetingTombstone],
        fileIDs: Set<String>
    ) -> [MeetingTombstone] {
        stones.filter { fileIDs.contains($0.id) }
    }
}

// MARK: - Неудавшийся старт

extension RecordingRecovery {
    /// Запись, от которой не осталось ни одного байта.
    ///
    /// Строка в индексе заводится **до** первого записанного байта — иначе
    /// начатая встреча несколько секунд не существовала бы в списке. Если
    /// захват так и не открылся (нет разрешения, агрегат не собрался) или
    /// процесс умер в первые секунды, остаётся строка в стадии `.recording`,
    /// у которой нет ни микса, ни стемов.
    ///
    /// Починить её нечем: `RecordingStage.recording.nextPhase` — nil, работы ей
    /// не причитается, а `hasSomethingToShow` для `.recording` истинно, так что
    /// из списка она не уходит. В рельсе это вечное «Идёт запись» с живой
    /// точкой, переживающее перезапуск, а в карточке — «В очереди». Две
    /// поверхности врут по-разному про одну встречу.
    ///
    /// Это не встреча, а след неудавшегося старта, и он убирается молча — как
    /// промах по кнопке в `SilentRecording`. С той же оговоркой: заметку,
    /// написанную руками, и транскрипт от прошлого прохода не стираем ничем.
    public static func isFailedStart(
        stage: RecordingStage,
        hasAnyAudio: Bool,
        hasTranscript: Bool,
        hasNotes: Bool
    ) -> Bool {
        stage == .recording && !hasAnyAudio && !hasTranscript && !hasNotes
    }
}
