    /// Baseline first, then the user's own terms from Settings. Case-insensitive
    /// dedupe so someone re-typing a term we already ship doesn't double it up;
    /// original spelling of the first occurrence wins.
    public static func merged(withUserTerms userTerms: [String]) -> [String] {
        var seen = Set<String>()
        var out: [String] = []
        for term in terms + userTerms {
            let clean = term.trimmingCharacters(in: .whitespacesAndNewlines)
            guard !clean.isEmpty else { continue }
            if seen.insert(clean.lowercased()).inserted {
                out.append(clean)
            }
        }
        return out
    }
