import Foundation

/// # Кто из двух дорожек звучал громче
///
/// Живой слой раздаёт имена по дорожкам: что пришло из микрофонной сессии,
/// сказал владелец. Это верно ровно до тех пор, пока микрофон слышит **только**
/// владельца — то есть пока человек в наушниках. На колонках микрофон слышит и
/// дальнюю сторону: замерено, `+27 dB` над собственным тихим полом, и из одной
/// микрофонной дорожки распознаётся **95.2 %** чужой речи
/// (`docs/ECHO_AND_MIX_EXPERIMENTS.md` §1). Тогда микрофонная сессия исправно
/// выдаёт чужие слова, а живая колонка подписывает их именем владельца — до
/// конца встречи.
///
/// Различить их можно, и не эмбеддингами. Системный стем снят **до** колонки, на
/// полном цифровом уровне; микрофон слышит ту же речь **после** комнаты, то есть
/// тише. Дорожки у нас выровнены кадр в кадр (`ProcessTapCapture`), поэтому
/// сравнивать их громкость в один и тот же момент законно — и этого достаточно.
///
/// Правило то же, что у готового транскрипта (`SourceAwareSpeaker.stemsOnly`):
/// **сомнение — в пользу дальней стороны.** Когда обе дорожки несут энергию, там
/// наверняка кто-то говорит, а «всё это я» — ровно тот провал, ради которого
/// правило и заведено. Цена ошибки несимметрична: потерянная реплика владельца
/// вернётся через две минуты финальным проходом, а приписанная ему чужая — это
/// то, что человек читает во время встречи и во что верит.
public struct StemDominance: Equatable, Sendable {

    /// Одно окно общей шкалы: сколько было в микрофоне и сколько в системной
    /// дорожке. Времена — секунды от начала записи, те же, что у реплик.
    struct Window: Equatable, Sendable {
        let start: Double
        let end: Double
        let mic: Float
        let system: Float
    }

    /// Тише этого — тишина, и окно не голосует вовсе. Не «порог речи»: он
    /// отсекает только цифровой ноль и шум пола, чтобы пауза между словами не
    /// решала, кто говорил.
    static let silenceFloor: Float = 0.003

    /// Сколько истории держим. Живая реплика приезжает через пару секунд после
    /// звука; минуты хватает с запасом, а встреча на восемь часов не имеет права
    /// расти в памяти.
    static let historySeconds: Double = 60

    private var windows: [Window] = []

    public init() {}

    /// Очередная порция захвата. Обе дорожки одного кадра — иначе сравнивать
    /// нечего.
    public mutating func note(from start: Double, to end: Double, mic: Float, system: Float) {
        guard end > start else { return }
        windows.append(Window(start: start, end: end, mic: mic, system: system))
        let cutoff = end - Self.historySeconds
        if let first = windows.first, first.end < cutoff {
            windows.removeAll { $0.end < cutoff }
        }
    }

    /// Владелец ли говорил в этом промежутке.
    ///
    /// `nil` — «не знаем»: окон на этот промежуток нет вовсе. Так бывает у самого
    /// начала записи и после переподключения сессии, и это **не** повод молчать:
    /// отсутствие замера не есть замер. Вызывающий в этом случае оставляет текст.
    public func ownerSpoke(from start: Double, to end: Double) -> Bool? {
        let heard = windows.filter { $0.end > start && $0.start < end }
            .filter { max($0.mic, $0.system) >= Self.silenceFloor }
        guard !heard.isEmpty else { return nil }
        let ownersOwn = heard.filter { $0.mic > $0.system }.count
        // Ровно половина — не большинство: сомнение в пользу дальней стороны.
        return ownersOwn * 2 > heard.count
    }
}
