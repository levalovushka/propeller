import Foundation

/// # Что слать один раз, а что каждый раз
///
/// Правила шумности телеметрии, отделённые от самих сигналов, потому что цена
/// ошибки здесь — неверное продуктовое решение, а не лишний байт трафика.
///
/// ## Чем это куплено
///
/// Замер 2026-08-21 читался как две катастрофы, и обе оказались лечением, а не
/// болезнью. `Pipeline.failed` в фазе `transcribing` — 37 событий у двух
/// человек; воронка показала, что **все пятеро** с такими отказами получили и
/// расшифровку, и саммари. `Ollama.setup.fail` — 28 событий у двенадцати; из
/// четырнадцати, у кого движок не встал, **одиннадцать** саммари всё же
/// получили. В обоих случаях сигнал считал попытки лестницы ретраев, а решение
/// требовалось про исход.
///
/// Отсюда правило: **инцидент сообщается один раз, исход — отдельно.** Тогда
/// «застряло» считается вычитанием, а не порогом, и ни одна ступень лестницы не
/// притворяется отдельной бедой.
public enum TelemetryNoise {

    /// Слать ли отказ фазы пайплайна.
    ///
    /// `attempt` — номер последовательного отказа этой фазы на этой записи
    /// (`PipelineFailure.attempt`, первый = 1). Ретраи бесконечны по построению,
    /// поэтому сообщать каждый — значит генерировать сигнал раз в час навсегда у
    /// того, у кого встреча действительно встала: чем безнадёжнее случай, тем
    /// громче он в статистике, хотя инцидент один.
    public static func reportsFailure(attempt: Int) -> Bool {
        attempt <= 1
    }

    /// Слать ли отказ установки движка саммари.
    ///
    /// У этого пути нет счётчика попыток: `ensureSummaryModel` заходит снова на
    /// каждом запуске и на каждой остановке пайплайна из-за провайдера, и каждый
    /// заход отчитывался как отдельный отказ. Состояние держит вызывающий — одна
    /// переменная на процесс; здесь только правило.
    ///
    /// Смена причины сообщается: `disk` после `pull` — другая поломка, и
    /// заглушить её значило бы потерять единственный сигнал о ней.
    public static func reportsSetupFailure(reason: String, lastReported: String?) -> Bool {
        reason != lastReported
    }

    /// Слать ли простой планировщика (`PipelineStall.Reason`).
    ///
    /// Счётчика попыток здесь нет и быть не может: цикл будится по таймеру
    /// каждые пять минут и по каждому наблюдаемому событию мира, а причина всё
    /// это время одна и та же. Сообщается смена состояния — «встали» и «встали
    /// уже по другой причине», — а не то, сколько раз мы посмотрели.
    ///
    /// `nil` в `reason` означает «инцидент кончился»: работа пошла. Дедупликацию
    /// держит вызывающий одной переменной на процесс, как у `reportsSetupFailure`.
    public static func reportsStall(reason: String, lastReported: String?) -> Bool {
        reason != lastReported
    }

    /// Слать ли смерть процесса на диаризации.
    ///
    /// Счётчик незакрытых попыток (`DiarizerAttempts`) лежит на диске и живёт до
    /// первого удачного возврата. Значит, у того, у кого кластеризация выключилась
    /// после двух смертей, он так и останется двойкой навсегда — и сообщать о нём
    /// на каждом запуске значило бы делать самый безнадёжный случай самым громким.
    ///
    /// Сообщается изменение: первая смерть, потом вторая, потом ничего.
    /// `lastReported` переживает перезапуск, иначе «изменение» не отличить от
    /// «увидели заново».
    public static func reportsDiarizerDeath(unfinished: Int, lastReported: Int?) -> Bool {
        unfinished > 0 && unfinished != lastReported
    }
}
