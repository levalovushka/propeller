import Foundation

/// # Что человек набрал, а приложение ещё не записало
///
/// Правка саммари уходит на диск через 0,8 с после последней клавиши
/// (`MainView.scheduleSummarySave`), заметка — только по ⏎. Между «набрал» и
/// «записано» стоит окно, и ⌘Q попадает ровно в него: при `terminate` SwiftUI
/// вьюхи не разбирает, `onDisappear` не приходит вовсе, и дописанный абзац
/// уходит вместе с процессом. Замерено поведением: дописал абзац, нажал ⌘Q —
/// абзаца нет.
///
/// Писать на каждую клавишу — не выход и не мелочь: файл лежит в чужом
/// хранилище, у которого свой наблюдатель, и запись на символ это
/// переиндексация на символ. Значит нужно второе: **одно место, которое знает,
/// что именно ещё не записано**, и которое можно спросить снаружи вьюхи — из
/// `applicationShouldTerminate`, где до `@State` не дотянуться никак.
///
/// Ключ, а не список замыканий: окно открывают и закрывают, и вторая
/// регистрация под тем же ключом обязана **заменить** первую. Иначе флаш на
/// выходе позвал бы вьюху, которой уже нет, и записал бы её последнюю правку
/// поверх свежей — тот же дефект, от которого защищается разрядка
/// `summarySave` после срабатывания.
@MainActor
public final class PendingEdits {

    /// Порядок регистрации хранится отдельно от замыканий: словарь его не
    /// помнит, а порядок здесь значащий — правка саммари пишет файл встречи,
    /// заметка пишет индекс, и второе обязано случиться после первого, чтобы
    /// один `flush()` индекса на выходе застал обе.
    private var keys: [String] = []
    private var handlers: [String: () -> Void] = [:]

    public init() {}

    /// Сколько мест сейчас может держать ненаписанное.
    public var count: Int { keys.count }

    public func register(_ key: String, flush: @escaping () -> Void) {
        if handlers[key] == nil { keys.append(key) }
        handlers[key] = flush
    }

    public func unregister(_ key: String) {
        keys.removeAll { $0 == key }
        handlers[key] = nil
    }

    /// Записать всё несохранённое. Возвращает, сколько мест спросили.
    ///
    /// Регистрации не снимает: приложение после флаша может и остаться жить
    /// (окно спрятали, машину усыпили), и снятая регистрация означала бы, что
    /// следующая правка в том же окне снова никому не видна.
    @discardableResult
    public func flush() -> Int {
        for key in keys { handlers[key]?() }
        return keys.count
    }
}
