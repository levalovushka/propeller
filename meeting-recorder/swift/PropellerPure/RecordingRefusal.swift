import Foundation

/// Почему записи нет, хотя её просили.
///
/// Одно перечисление, а не два разрозненных флага, потому что для человека это
/// один случай: он нажал «Новая запись», и встречи не пишется. Разница только в
/// том, что чинить — и, значит, куда ведёт клик по строке.
///
/// Отнятый микрофон это умел давно: состояние садилось на приложение и ждало в
/// рельсе на месте «Новой записи», пока разрешение не изменится. А отказ самого
/// захвата (`recorder.start()` бросил) `beginRecording` глотал целиком — ни
/// строки, ни лога: человек нажимал кнопку, и не происходило ничего. Тем же
/// путём терялся и снятый воркер: `pausePipeline()` зовётся до `try`, а кика
/// назад в ветке отказа не было, и архив стоял до следующего события.
///
/// Здесь, в `PropellerPure`, ради теста: `Sources/` — исполняемая цель, её не
/// импортирует ни один тест, а слова, которые человек читает, обязаны быть
/// проверяемыми.
public enum RecordingRefusal: String, Equatable, Sendable, CaseIterable {
    /// Микрофон не наш: разрешение не выдано или отозвано.
    case microphone
    /// Захват не поднялся: устройство отобрали, вход занят, файл не открылся.
    case captureFailed

    /// Что стоит в рельсе на месте «Новой записи», пока отказ не снят.
    ///
    /// Состояние, а не сообщение: пуш надо успеть прочитать в ту секунду, когда
    /// он вышел, а эту строку человек находит там, куда идёт спрашивать, почему
    /// встреча не записалась.
    public var railTitle: String {
        switch self {
        case .microphone:    return "Нет доступа к\u{00A0}микрофону"
        case .captureFailed: return "Запись не началась"
        }
    }

    public var railSymbol: String {
        switch self {
        case .microphone:    return "mic.slash"
        case .captureFailed: return "exclamationmark.triangle"
        }
    }

    /// Может ли клик по строке сам всё исправить.
    ///
    /// У микрофона — нет: разрешение выдаётся в системных настройках, и строка
    /// ведёт туда. У захвата — да, и это тот же «Новая запись»: устройство
    /// вернулось, вход освободился, вторая попытка ничего не стоит.
    public var retryStartsRecording: Bool {
        switch self {
        case .microphone:    return false
        case .captureFailed: return true
        }
    }

    /// Снят ли перед этим отказом воркер догона.
    ///
    /// `pausePipeline()` стоит внутри `beginRecording`, то есть до микрофонной
    /// проверки воркера никто не трогал, а после отказа захвата — трогал и не
    /// вернул. Ответ нужен на месте вызова, поэтому он здесь, рядом с причиной,
    /// а не в памяти того, кто пишет `catch`.
    public var leavesPipelinePaused: Bool {
        switch self {
        case .microphone:    return false
        case .captureFailed: return true
        }
    }
}
