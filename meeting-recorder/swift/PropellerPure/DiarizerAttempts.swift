import Foundation

/// # Сколько раз диаризация имеет право убить процесс
///
/// Кластеризация FluidAudio исполняется CoreML **в нашем процессе**, и на
/// macOS 14.8.4 она уводит его в `SIGBUS` внутри BNNS. Сигнал не перехватывается:
/// `do/catch` вокруг вызова не существует, `Task` не спасает, спросить «получилось
/// ли» не у кого — процесса больше нет.
///
/// Отсюда правило, которое не про CoreML вовсе: **работа, способная убить процесс,
/// обязана оставить след до того, как её начнут.** След переживает смерть, а
/// возвращение к жизни его читает. Иначе получается то, что получилось у
/// тестировщика: пайплайн при каждом запуске берёт ту же встречу, доходит до того
/// же места и умирает — 35 запусков и 25 отчётов о падении за трое суток, и ни
/// одного способа выйти изнутри.
///
/// Два раза, а не один: одно незакрытое начало может остаться от обычного выхода
/// посреди работы (человек нажал ⌘Q, машина уснула, кончилось питание). Два подряд
/// — это уже не совпадение. Тот же счёт, что у `GigasttSidecar.consecutiveCrashRestarts`,
/// и по той же причине.
///
/// Что происходит после отказа — не «ошибка», а глубина: встреча получает спикеров
/// по дорожкам («Левон / Собеседник», `SpeakerAttribution.stems`), путь для этого
/// уже есть и уже проверен (`design/no-dead-ends.md`, Э1). Расшифровка не теряется,
/// потому что она к этому моменту уже на диске.
public struct DiarizerAttempts: Equatable, Sendable {

    /// Начатых и не закрытых попыток. Растёт перед вызовом, обнуляется после.
    public private(set) var unfinished: Int

    /// Сколько смертей подряд считаем случайностью.
    public static let limit = 2

    public init(unfinished: Int = 0) {
        self.unfinished = max(0, unfinished)
    }

    /// Можно ли ещё пробовать. `false` — диаризацию на этой машине не зовём вовсе.
    public var mayRun: Bool { unfinished < Self.limit }

    /// Записывается **до** вызова и обязано долететь до диска раньше него.
    public mutating func starting() { unfinished += 1 }

    /// Вызов вернулся — чем бы ни кончился. Даже брошенная ошибка означает, что
    /// процесс жив, а считаем мы только смерти.
    public mutating func returned() { unfinished = 0 }
}
