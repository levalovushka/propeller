import Foundation

/// # Что говорит строка клиента в настройках
///
/// Состояние **выводится**, не хранится: читаем чужой конфиг и отметку в момент
/// открытия настроек. Хранить его значило бы завести второй источник правды о
/// том, что лежит в чужом файле, — и разойтись с ним ровно тогда, когда чужое
/// приложение этот файл перепишет.
///
/// Здесь и решение, и слова: тест ставит «запись есть, отметки нет» и видит
/// строку, которую увидит человек. Тот же приём, что у `SetupPrompt`, и по той
/// же причине — цена ошибки тут не «некрасиво», а «человек застрял в состоянии,
/// из которого не видно выхода».
///
/// Состояния общие на всех клиентов, слова — нет: см. `subtitle(for:)`.
public enum MCPCellState: String, CaseIterable, Equatable, Sendable {
    /// Клиента на машине нет. Предлагать нечего — только сказать, что бывает.
    case notInstalled
    /// Всё готово к нажатию.
    case offer
    /// Запись в конфиге есть, но клиент её ещё не прочитал.
    case restartNeeded
    /// Он нас запустил хотя бы раз.
    case connected
    /// Запись из конфига пропала, а отметка осталась. Чаще всего это значит,
    /// что клиент переписал свой конфиг целиком (известные репорты у Клода —
    /// Windows и Linux; для macOS подтверждения нет).
    case lost
    /// Последняя попытка записать конфиг не удалась. Причину разбираем мы, по
    /// телеметрии; человеку её знать незачем.
    case writeFailed

    /// Тихая вторая строка — единственное, что меняется.
    ///
    /// Имя приложения в ней не повторяется: оно уже стоит заголовком слева.
    /// Исключение одно — просьба перезапустить: у неё есть адресат, и «просто
    /// перезапустите» не говорит кого, притом что на экране в этот момент три
    /// приложения сразу (Propeller, клиент и то, где человек работает).
    ///
    /// У отказа записи подписи нет вовсе, и это решение владельца: сказать по
    /// делу нечего — причина уехала в телеметрию, разбираемся мы, — а «не
    /// получилось» слово в слово повторяет то, что и так написано на кнопке.
    public func subtitle(for client: MCPClient) -> String? {
        switch self {
        case .notInstalled:
            return "Не установлен — приложение с\u{00A0}сайта \(client.vendor)"
        case .offer:
            return "Сможет читать ваши встречи"
        // Единственное место, где клиенты расходятся словами, и расходятся они
        // не косметически. У Клода это просьба к человеку: он поднимет сервер
        // на своём старте, и до перезапуска ничего не случится. У ChatGPT
        // просить нечего — Codex возьмёт сервер, когда он ему понадобится, и
        // перезапуск этого не приблизит. Просьба, которая ничего не ускоряет,
        // это враньё в интерфейсе.
        case .restartNeeded:
            return client.startsEagerly
                ? "Перезапустите \(client.rowTitle), чтобы он увидел встречи"
                : "Готов — \(client.rowTitle) возьмёт встречи при первом вопросе"
        case .connected:
            return "Подключён"
        // Конкретнее, чем «подключение потерялось», и верно в обоих случаях,
        // которыми это бывает: запись пропала из чужого конфига (его переписал
        // сам клиент) или путь в ней указывает в пустоту, потому что Propeller
        // переехал. Подпись читается вместе с заголовком строки — «Claude
        // Desktop · Больше не видит Propeller», — поэтому подлежащее не нужно.
        case .lost:
            return "Больше не видит Propeller"
        case .writeFailed:
            return nil
        }
    }

    /// Подпись кнопки — или nil, когда нажимать не на что.
    ///
    /// Кнопки нет в двух состояниях, и оба раза потому, что нажатие ничего не
    /// изменило бы: у «перезапустите» очередь за человеком и его чатами,
    /// у «подключён» — всё уже сделано. Кнопки «Перезапустить» нет намеренно:
    /// закрывать чужое приложение с открытыми разговорами мы не будем.
    public var actionTitle: String? {
        switch self {
        case .offer, .lost: return "Подключить"
        // Кнопка и есть сообщение об отказе: «снова» говорит, что попытка уже
        // была и не удалась, — поэтому второй строки у этого состояния нет.
        case .writeFailed:  return "Попробовать снова"
        case .notInstalled, .restartNeeded, .connected: return nil
        }
    }

    public var showsCheckmark: Bool { self == .connected }

    /// Хвост имени кадра в галерее и в Figma. Своё, а не `rawValue`:
    /// идентификаторы кадров живут в именах файлов, и там разрешены только
    /// `[a-z0-9-]` (`UIStateCatalogTests`). Голова — из `MCPClient.rawValue`.
    public var slug: String {
        switch self {
        case .notInstalled:  return "not-installed"
        case .offer:         return "offer"
        case .restartNeeded: return "restart-needed"
        case .connected:     return "connected"
        case .lost:          return "lost"
        case .writeFailed:   return "write-failed"
        }
    }
}

public enum MCPCellMachine {

    /// Единственное место, где решается, что человек увидит.
    ///
    /// Порядок веток — порядок правды. Не установлен — про конфиг говорить
    /// нечего, чей бы он ни был. Не записался — это ответ на нажатие, и он
    /// старше вывода из файлов. Дальше таблица: запись в конфиге × отметка.
    ///
    /// Состояния «клиент перезапустился, но не подключился» здесь нет и быть не
    /// может: отметки просто нет, и почему — мы не знаем. Поэтому ожидание
    /// живёт до появления отметки, а не превращается в ошибку по таймеру.
    public static func state(
        installed: Bool,
        configured: Bool,
        markedAt: Date?,
        lastWriteFailed: Bool
    ) -> MCPCellState {
        guard installed else { return .notInstalled }
        if lastWriteFailed { return .writeFailed }
        switch (configured, markedAt != nil) {
        case (true, true):   return .connected
        case (true, false):  return .restartNeeded
        case (false, true):  return .lost
        case (false, false): return .offer
        }
    }
}
