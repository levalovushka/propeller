import Foundation

/// # У какой встречи можно забрать аудио
///
/// Аудио — самое тяжёлое, что есть у встречи, и единственное, что она умеет
/// потерять без потери смысла: расшифровка и саммари остаются, и встреча читается
/// как любая другая (`RecordingStore.deleteAllReclaimableAudio`). Но это верно не
/// для всякой встречи, и обе оговорки — про необратимое.
///
/// **Аудио — вход двух фаз.** ASR и диаризация читают файл (`Phase.needsAudio`), и
/// у встречи, которой они ещё причитаются, удаление аудио отнимает не место, а
/// саму встречу: `owedPhase` вернёт nil, воркер пройдёт мимо, и она останется
/// нерасшифрованной навсегда. Именно так выглядит состояние `11-failed` —
/// «дальше нечего делать, аудио удалено».
///
/// **Аудио — иногда единственное, что есть.** Список показывает встречу, если у
/// неё есть текст или есть файл (`hasSomethingToShow`). Забрать файл у встречи
/// без текста — значит убрать её из списка: не удалить (индекс останется), а
/// именно спрятать, без двери назад.
///
/// Поэтому правило спрашивает про текст, а не про стадию: стадия отвечает на
/// первый вопрос, текст — на второй, и порог `>= .transcribed` руками ответил бы
/// на оба неточно.
public enum AudioReclaim {

    /// Можно ли забрать аудио у встречи, ничего ей не сломав.
    ///
    /// `stage` спрашивается через `nextPhase`, а не сравнением со ступенью:
    /// появится фаза, которой понадобится звук, — правило поедет за ней само.
    public static func isExpendable(stage: RecordingStage, hasTranscript: Bool) -> Bool {
        // Идущая запись как раз пишет в этот файл. Её `nextPhase` — nil, потому
        // что воркеру она пока не причитается вовсе, так что без этой проверки
        // она попала бы в «аудио больше не нужно» первой.
        guard stage != .recording else { return false }
        guard hasTranscript else { return false }
        return stage.nextPhase?.needsAudio != true
    }

    /// Можно ли предложить «Удалить аудио» рукой, в меню встречи.
    ///
    /// Тот же вопрос, что у ретеншена и у «Очистить», плюс один: есть ли что
    /// удалять. До 2026-08-31 пункт меню спрашивал **только** второе — и у
    /// нерасшифрованной встречи был активен. Нажатие уносило файл: текста нет,
    /// записи нет, аудио нет, значит `hasSomethingToShow` ложно во всех трёх
    /// ветках — строка уходила из рельса, работа переставала причитаться
    /// (`audioAvailable`), а из индекса встреча не уходила. Двери назад не было
    /// ни одной.
    ///
    /// Автоматические пути этой ошибки не знали, потому что оба спрашивали
    /// `isExpendable`. Рука не спрашивала никого — и именно у руки цена ошибки
    /// выше: там встреча выбрана человеком поимённо.
    public static func isManuallyDeletable(
        stage: RecordingStage, hasTranscript: Bool, audioExists: Bool
    ) -> Bool {
        audioExists && isExpendable(stage: stage, hasTranscript: hasTranscript)
    }
}
