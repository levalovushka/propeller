import Foundation

/// # Где заметка стоит среди реплик
///
/// Заметка пишется во время разговора и относится к его месту, а не к концу
/// списка. Значит расшифровка — это не «реплики, а под ними заметки», а одна
/// лента, в которой и то и другое стоит на своей секунде.
///
/// Правило живёт здесь, а не в колонке, по двум причинам. Колонок две — живая и
/// готовая, — и разное правило означало бы, что одна и та же встреча до стопа и
/// после него собрана по-разному; это уже случалось с разбивкой на реплики, и
/// поэтому `LiveTranscript` берёт `turnGapSeconds` у `TranscriptPresentation`, а
/// не заводит свой. Вторая причина обычная: порядок можно проверить тестом
/// только там, где нет AppKit.
///
/// Отдаётся здесь **порядок**, а не собранные строки: тексты у живой и у готовой
/// колонки разные (одна дописывает хвост, вторая знает спикеров), а вопрос
/// «что за чем» у них общий и ровно один.
public enum NotePlacement {

    /// Один элемент ленты — ссылка на реплику или на заметку в исходных списках.
    public enum Item: Hashable, Sendable {
        case turn(index: Int)
        case note(index: Int)
    }

    /// Слить реплики и заметки в одну ленту по времени.
    ///
    /// - Parameters:
    ///   - turnStarts: начала реплик, в том порядке, в каком их показывают.
    ///     Порядок принимается как есть и не пересортировывается: колонка уже
    ///     решила, что за чем, и решать это второй раз здесь — способ разойтись
    ///     с ней на встрече, где спикеры перебивают друг друга.
    ///   - noteOffsets: время заметок. `nil` — у заметки времени нет, и в ленту
    ///     она не попадает вовсе: это заметка, дописанная после встречи, и любая
    ///     секунда для неё выдумана. Её место — саммари.
    ///
    /// Заметка на той же секунде, что и реплика, встаёт **после** реплики:
    /// её пишут про то, что только что услышали, — это отклик на сказанное, а
    /// не анонс следующего.
    public static func interleave(turnStarts: [Double], noteOffsets: [Double?]) -> [Item] {
        // Заметки сортируются, реплики — нет. Дописываются они по одной и почти
        // всегда идут по возрастанию, но «почти» — не то слово, на котором
        // строят порядок: у заметки из старого архива время прочитано из её
        // собственного текста и может оказаться каким угодно.
        var placed: [(index: Int, at: Double)] = []
        for (index, offset) in noteOffsets.enumerated() {
            guard let offset else { continue }
            placed.append((index: index, at: offset))
        }
        placed.sort { $0.at == $1.at ? $0.index < $1.index : $0.at < $1.at }

        var feed: [Item] = []
        feed.reserveCapacity(turnStarts.count + placed.count)
        var next = 0
        for (turnIndex, start) in turnStarts.enumerated() {
            while next < placed.count, placed[next].at < start {
                feed.append(.note(index: placed[next].index))
                next += 1
            }
            feed.append(.turn(index: turnIndex))
        }
        // Всё, что после последней реплики, — и то, что написано в тишине в
        // конце встречи, и все заметки встречи, у которой реплик нет вовсе.
        while next < placed.count {
            feed.append(.note(index: placed[next].index))
            next += 1
        }
        return feed
    }
}
