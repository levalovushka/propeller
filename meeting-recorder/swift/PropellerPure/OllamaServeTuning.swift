import Foundation

/// # Память бэкфилла: prompt cache llama-server выключен
///
/// Замер Г4 (2026-08-15, стенд 52 встречи): память ollama-семейства росла
/// монотонно 5,0 → 12,3 ГБ за ~40 минут при неизменном `ollama ps`. Причина —
/// не наши окна и не чехарда раннеров: **prompt cache llama.cpp**
/// (`--cache-ram`, по умолчанию 8192 MiB) оставляет в RAM KV-стейт каждого
/// отработанного промпта — 8107 токенов = 354 MiB, ~44 КБ на токен. За 69
/// вызовов сокращённого прогона кэш дорос до 22 промптов / 5483 MiB в одном
/// llama-server (PID один, RSS 5,2 → 10,2 ГБ).
///
/// Кэш окупается только повторением **идентичного префикса**. У конспекта
/// таких повторов почти нет: каждый вызов — новая встреча, новый фрагмент или
/// другой системный промпт. Единственный настоящий повтор — ретрай
/// схлопнувшегося ответа (t=0,3 сразу после t=0), и он платит одну
/// переоценку промпта (~9 с на 8k токенов, 859 ток/с замерено) — раз в
/// редкое схлопывание, а не 8 ГБ резидента на каждый бэкфилл.
///
/// Почему env, а не флаг: `ollama serve` сам поднимает llama-server и своего
/// `--cache-ram` не передаёт (проверено по командной строке раннера), а
/// llama.cpp читает `LLAMA_ARG_CACHE_RAM` как значение по умолчанию для
/// флага. Дети наследуют окружение серва — env доезжает.
///
/// Границы: действует только на серв, **поднятый приложением**. Чужой Ollama
/// (adopt-if-present на :11434) остаётся со своим кэшем — его окружение не
/// наше. Живой путь не платит ничего: холодные загрузки, окна и промпты не
/// меняются, выключается только удержание отработанных стейтов.
public enum OllamaServeTuning {

    /// `0` — выключить удержание целиком. Не «маленький лимит»: даже 512 MiB
    /// на приёмке Г4 (пик ≤ 6,5 ГБ при базе 32k-раннера 5,8) съели бы весь
    /// запас.
    public static let extraEnvironment: [String: String] = [
        "LLAMA_ARG_CACHE_RAM": "0"
    ]

    /// Окружение серва с тюнингом поверх. Ключи, которые приложение уже
    /// выставило (OLLAMA_HOST, OLLAMA_MODELS, DYLD_LIBRARY_PATH), не трогаются:
    /// тюнинг добавляет свои и не смеет спорить с адресом сервера.
    public static func apply(to base: [String: String]) -> [String: String] {
        var env = base
        for (key, value) in extraEnvironment where env[key] == nil {
            env[key] = value
        }
        return env
    }
}
