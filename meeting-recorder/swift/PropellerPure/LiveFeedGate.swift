import Foundation

/// # Что не имеет смысла отдавать движку
///
/// Живая строка стоит дорого не потому, что распознавание тяжёлое, а потому что
/// оно работает **всю встречу**: две сессии, 0.41 ядра и 1.34 Гцикла на секунду
/// звука (`benchmarks/baseline.json`, ключи `live.*`). И платится это за время, а
/// не за речь — 28 секунд цифровой тишины стоят ровно столько же, сколько 28
/// секунд разговора (замерено 2026-08-10, `Bench --live`). Значит порция, в
/// которой заведомо нечего распознавать, — это чистый счёт за электричество.
///
/// Таких порций две разновидности, и обе видны из уже посчитанных чисел.
///
/// **Тишина.** Громкость обеих дорожек уже считается на каждом кадре
/// (`LiveTranscriptService.LoudnessLog`), и порог, ниже которого «никто не
/// говорит», — `FeedGate.silenceFloor`, один на весь живой слой. Реального
/// созвона это касается сильно: на фикстуре с паузами микрофонная дорожка молчит
/// 47 % времени, системная — 66 %.
///
/// **Чужая речь в микрофоне.** На колонках микрофон слышит дальнюю сторону, и из
/// него распознаётся 95–97 % её слов (`docs/ECHO_AND_MIX_EXPERIMENTS.md` §1).
/// Эти слова распознаются полностью, а потом выбрасываются: на экран их не
/// пускает `EchoDedup` — реплика владельца, уже сказанная дальней стороной, не
/// показывается. То есть работа делается ради результата, про который заранее
/// известно, что он пойдёт в мусор. Гейт — это тот же вопрос, заданный **до**
/// отправки, а не после ответа, и поэтому он не может изменить того, что человек
/// видит на экране.
///
/// Как отличить эхо от своей речи — вопрос отдельный и решённый замером:
/// сравнением громкостей нельзя (собственный голос владельца в его микрофоне
/// тише эха на 4–6 dB), поэтому спрашивается когерентность с референсом,
/// `EchoCoherence`.
///
/// # Почему решение принимается по целой порции
///
/// Порция — две секунды, и это замер, а не вкус: 9.7 % WER против 25 % на 200 мс
/// (`tools/live-bench/README.md`). Выкусывать тишину внутри порции нельзя — тогда
/// движку достанется склейка несмежных кусков речи, то есть щелчок посреди слова.
/// Поэтому решение одно на порцию: **тишина — если молчат все её окна; эхо — если
/// её громкие ячейки объясняются дальней стороной.** Заодно это бесплатно даёт
/// разбег: слово, начавшееся в последних миллисекундах порции, приезжает вместе с
/// предшествующей тишиной, и отдельный preroll-буфер не нужен.
///
/// Асимметрия дорожек намеренная: системный стем снят до колонки, владельца в
/// нём быть не может, поэтому там спрашивается только тишина. Микрофон — оба
/// вопроса.
public struct FeedGate: Sendable {

    /// Какие из двух правил включены.
    ///
    /// Раздельно, потому что они покупают разное за разную цену, и это надо было
    /// увидеть по отдельности, а не одним числом: тишина даёт больше экономии, а
    /// эхо не может изменить того, что на экране, — его результат и сегодня
    /// выбрасывается. Замеры каждого варианта — в `benchmarks/report-gate.md`.
    public struct Rules: OptionSet, Sendable {
        public let rawValue: Int
        public init(rawValue: Int) { self.rawValue = rawValue }

        /// Не отдавать порцию, в которой обе дорожки ниже порога тишины.
        public static let silence = Rules(rawValue: 1 << 0)
        /// Не отдавать микрофонной сессии порцию, где уверенно говорит дальняя
        /// сторона.
        public static let echo = Rules(rawValue: 1 << 1)

        public static let both: Rules = [.silence, .echo]
    }

    public let rules: Rules

    /// Тише этого — тишина, и окно не считается. Не «порог речи»: он отсекает
    /// только цифровой ноль и шум пола, чтобы пауза между словами ничего не
    /// решала. Один на весь живой слой — заводить второй значит получить два
    /// разных ответа на вопрос «здесь кто-нибудь говорит».
    public static let silenceFloor: Float = 0.003

    /// # Разбега здесь нет, и это замер, а не упущение
    ///
    /// Гейт теряет **первое короткое слово реплики**: «Да, я помню про биллинг»
    /// приезжает как «я помню про биллинг», «Отлично. Спасибо» — как «Спасибо»
    /// (coverage 0.976 → 0.952 на `ru-pauses-2spk`). Напрашивающееся объяснение —
    /// движок потоковый, и порция, в которой начинается речь, приходит к нему
    /// первой после разрыва, «холодной». Напрашивающееся лечение — приклеить к ней
    /// пропущенную тишину.
    ///
    /// Проверено: **не помогает.** Полсекунды разбега — coverage те же 0.952, цена
    /// 0.26 → 0.28 ядра. Целая порция разбега — те же 0.952, цена 0.29 и `fed`
    /// 0.834 вместо 0.687, то есть половина экономии отдана ни за что. Причина не
    /// в холодном старте: порция с началом слова **отправляется** (проверено
    /// пересчётом решений гейта по фикстуре) — движок просто иначе решает на
    /// границе, когда перед ней был выброшен звук. Разбегом это не лечится, и
    /// добавлять его «на всякий случай» значит платить за версию причины, которая
    /// оказалась неверной.
    ///
    /// Через сколько молчания отдать порцию просто чтобы сокет не закрыли.
    ///
    /// Сервер закрывает сессию, если кадров не было `--idle-timeout-secs`, а это
    /// **300 с** по умолчанию (`gigastt serve --help`). Человек, который молча
    /// слушает чужой монолог шесть минут, не должен из-за экономии потерять
    /// сессию: переподключение стоит дороже одной порции, и до `ready` оно ещё и
    /// теряет звук. 240 с — тот же порог с минутой запаса.
    public static let keepaliveSeconds: Double = 240

    /// Какой доли необъяснённых ячеек хватает, чтобы отдать порцию микрофонной
    /// сессии.
    ///
    /// Замер 2026-08-11 (окна 2 с, 711 с эхом, 124 чистых владельца): только эхо
    /// — 0.05, эхо со речью владельца на −10 dB — 0.22, на −5 dB — 0.29, только
    /// владелец — 0.74. Порог стоит **ниже двойного разговора на самом
    /// невыгодном для нас уровне**, а не посередине: пропущенная порция стоит
    /// слова, а лишняя — только электричества, и цена этих ошибок несимметрична.
    public static let ownerShare: Double = 0.15

    /// На каком отрезке задаётся этот вопрос. Полсекунды — длина слова: короче
    /// голосов не хватает на суждение, длиннее — короткая перебивка владельца
    /// растворяется в чужой речи.
    public static let decisionSeconds: Double = 0.5
    /// Меньше этого числа голосов отрезок не судит: доля от десятка ячеек — это
    /// шум, а не замер.
    public static let minimumCells = 20

    /// Окно захвата — одно тиканье дрейна (50 мс): громкость обеих дорожек и
    /// голоса ячеек время-частота, посчитанные `EchoCoherence`.
    public struct Window: Equatable, Sendable {
        public let start: Double
        public let end: Double
        public let mic: Float
        public let system: Float
        /// Сколько громких ячеек пришлось на это окно и сколько из них дальняя
        /// сторона не объясняет. По умолчанию — «замера когерентности нет»
        /// (микрофонный путь без системной дорожки, начало записи), и тогда
        /// правило эха молчит.
        public let cells: EchoCoherence.Cells

        public init(
            start: Double, end: Double, mic: Float, system: Float,
            cells: EchoCoherence.Cells = .none
        ) {
            self.start = start
            self.end = end
            self.mic = mic
            self.system = system
            self.cells = cells
        }

        var silent: Bool { max(mic, system) < FeedGate.silenceFloor }
    }

    public init(rules: Rules = .both) {
        self.rules = rules
    }

    /// # Что ещё пробовали и отвергли
    ///
    /// Гейт съедает **первое короткое слово реплики** — «Хорошо», «Отлично»,
    /// «Да» (coverage 0.976 → 0.952 на `ru-pauses-2spk`). Две попытки это
    /// вылечить, обе отвергнуты замером, и обе стоит помнить, потому что каждая
    /// звучит убедительно:
    ///
    /// **Разбег** — приклеить к включающей порции пропущенную тишину, чтобы
    /// движок входил в фразу «тёплым». Не помогает: полсекунды — те же 0.952 при
    /// цене 0.26 → 0.28 ядра; целая порция — те же 0.952 при `fed` 0.834 вместо
    /// 0.687, то есть половина экономии отдана ни за что. Причина не в холодном
    /// старте: порция с началом слова **отправляется**, это проверено пересчётом
    /// решений гейта по фикстуре.
    ///
    /// **Выравнивание по началу речи** — не отдавать порцию «1.9 с тишины +
    /// огрызок», а перенести начало речи в следующую, целую. Слова возвращает
    /// («Да» и «Отлично» на месте) и даёт самый дешёвый прогон из всех — 0.22
    /// ядра, минус 48 %. И ломает границы **внутри** фраз, потому что сдвигает
    /// сетку порций: WER 0.241 против 0.181, «миграцию» приезжает как
    /// «ми ми ми ми миграци», а вместо трёх потерянных слов теряются пять
    /// других. Обменять начала фраз на их середины — не лечение.
    ///
    /// Вывод, который стоит уважать: **потеря первого слова — свойство дробления
    /// потока, а не ошибка гейта.** Движок держит состояние между порциями и на
    /// границе решает иначе, когда перед ней выброшен звук. Уменьшать это можно
    /// только уменьшая число разрывов — то есть отказываясь от части экономии.
    ///
    /// - Parameters:
    ///   - windows: окна, попадающие в порцию. Пустой список — «замера нет»,
    ///     и тогда порция уходит: отсутствие замера не есть замер, и это то же
    ///     правило, по которому `EchoDedup` показывает реплику, когда сравнивать
    ///     её не с чем.
    ///   - secondsSinceLastSend: сколько молчит эта сессия. Нужно только для
    ///     keepalive.
    public func shouldSend(
        channel: LiveTranscript.Channel,
        windows: [Window],
        secondsSinceLastSend: Double
    ) -> Bool {
        if secondsSinceLastSend >= Self.keepaliveSeconds { return true }
        guard !windows.isEmpty else { return true }

        let audible = windows.filter { !$0.silent }

        // Тишина: в порции не звучит ни одна дорожка.
        if audible.isEmpty { return !rules.contains(.silence) }

        // Эхо: в порции звучит только то, что объясняется дальней стороной.
        guard channel == .owner, rules.contains(.echo) else { return true }
        // Замера когерентности нет — порция уходит. Отсутствие замера не есть
        // замер, и на микрофонном пути (нет системной дорожки) так будет всегда.
        guard audible.contains(where: { $0.cells.loud > 0 }) else { return true }

        // Решение — по отрезку в полсекунды, скользящему по порции.
        //
        // Ни по целой порции, ни по одному окну. По целой — короткая перебивка
        // владельца растворяется: полсекунды его речи среди двух секунд чужой
        // дают долю 0.11 при пороге 0.15, и слово пропадает. По одному окну в
        // 50 мс — голосов слишком мало, чтобы каждое решало само. Полсекунды —
        // длина слова, то есть наименьшее, что имеет смысл спасать.
        var loud = 0
        var unexplained = 0
        var low = 0
        for high in audible.indices {
            loud += audible[high].cells.loud
            unexplained += audible[high].cells.unexplained
            while low < high, audible[high].end - audible[low].start > Self.decisionSeconds {
                loud -= audible[low].cells.loud
                unexplained -= audible[low].cells.unexplained
                low += 1
            }
            guard loud >= Self.minimumCells else { continue }
            if Double(unexplained) / Double(loud) >= Self.ownerShare { return true }
        }
        return false
    }
}

/// # Шкала времени, когда часть звука не отдана
///
/// Движок считает времена слов **от своего нуля и по полученным кадрам**: он не
/// знает про пропуски и не может знать — `configure` после первого кадра
/// запрещён (`configure_too_late`), а нового сокета мы ради этого не открываем.
/// Значит, как только гейт пропустил порцию, серверное время и время встречи
/// разошлись на её длину, и дальше расходятся с каждым пропуском.
///
/// Без этой карты весь дальнейший текст лёг бы **раньше**, чем был сказан, —
/// поверх уже показанного. Это худший из возможных исходов экономии: не «текста
/// меньше», а «текст врёт про то, когда это было», причём тем сильнее, чем
/// дольше идёт встреча.
///
/// Карта хранит не каждую порцию, а только моменты, когда смещение изменилось:
/// восьмичасовая встреча без пропусков — это одна запись, а не четырнадцать
/// тысяч.
public struct FedTimeline: Equatable, Sendable {

    private struct Mark: Equatable, Sendable {
        /// Секунда, с которой этот отрезок начинается в шкале движка.
        let server: Double
        /// Та же секунда в шкале встречи.
        let meeting: Double
    }

    private var marks: [Mark] = []
    /// Сколько звука уже отдано движку — это и есть его собственная шкала.
    private var fedSeconds: Double = 0
    /// Сколько пропущено. Только для счёта: сдвиг шкалы выводится из того, где
    /// начинаются отданные порции, а не из этой суммы — иначе получаются два
    /// источника правды об одном смещении, и они расходятся.
    private var skippedSeconds: Double = 0

    public init() {}

    public var totalSkippedSeconds: Double { skippedSeconds }

    /// Порция ушла движку. `meetingStart` — её начало в шкале встречи.
    public mutating func fed(meetingStart: Double, seconds: Double) {
        guard seconds > 0 else { return }
        let offset = meetingStart - fedSeconds
        let previous = marks.last.map { $0.meeting - $0.server }
        // Запись нужна только там, где смещение изменилось: пока порции идут
        // подряд, продолжать прежний отрезок арифметически то же самое.
        if previous == nil || abs(offset - previous!) > 1e-9 {
            marks.append(Mark(server: fedSeconds, meeting: meetingStart))
        }
        fedSeconds += seconds
    }

    /// Порция не ушла. Отдельный метод, а не молчание, потому что «пропустили»
    /// — это событие, которое надо уметь посчитать (`live.frames_fed_ratio`).
    public mutating func skipped(seconds: Double) {
        guard seconds > 0 else { return }
        skippedSeconds += seconds
    }

    /// Секунда встречи, которой соответствует секунда `server` в шкале движка.
    ///
    /// До первой отданной порции карта пуста, и ответ — само `server`: смещаться
    /// ещё некуда, а возвращать `nil` значило бы заставить каждый вызывающий код
    /// придумывать, куда девать текст.
    public func meetingTime(forServer server: Double) -> Double {
        guard let mark = lastMark(atOrBefore: server) else { return server }
        return mark.meeting + (server - mark.server)
    }

    private func lastMark(atOrBefore server: Double) -> Mark? {
        guard !marks.isEmpty else { return nil }
        // Двоичный поиск: карта растёт с каждым включением гейта, а спрашивают
        // её на каждый финал.
        var low = 0
        var high = marks.count - 1
        var found: Mark?
        while low <= high {
            let mid = (low + high) / 2
            if marks[mid].server <= server + 1e-9 {
                found = marks[mid]
                low = mid + 1
            } else {
                high = mid - 1
            }
        }
        // Спросили время раньше первой отданной порции — отвечаем первой.
        return found ?? marks[0]
    }
}
