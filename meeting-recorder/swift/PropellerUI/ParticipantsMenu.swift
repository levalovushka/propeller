import PropellerPure
import SwiftUI

/// # Состав встречи — меню под чипом «6 человек»
///
/// Щелчок по чипу открывает **системное меню**, а не нарисованную плиту, и это
/// решение владельца 2026-08-27, принятое после разбора: всё, что является
/// списком команд, остаётся системным — «именно везде», без смешения двух
/// грамматик в одном приложении.
///
/// Первый заход был своей плитой (Figma `summary/participants`, 285:19438) с
/// крестиком по ховеру и полем ввода в ряду. Она работала, и её сняли по
/// решению, а не из-за дефекта. Что при этом стало невыразимым — названо, а не
/// забыто:
///
/// - **крестика по ховеру у пункта меню не бывает**, поэтому «убрать» переехало
///   в подменю участника: у объекта своё действие рядом с ним, а не отдельным
///   списком тех же имён;
/// - **поля ввода внутри меню не бывает**, и это не наша беда: `NSMenu` не
///   отдаёт нажатия клавиш виду внутри себя (сэмпл Apple CustomMenus говорит это
///   прямо, а `addLocalMonitorForEvents` по документации во время menu tracking
///   не зовётся). Поэтому «Добавить» предлагает уже известных людей, а нового
///   человека печатать негде — это ждёт своей плиты создания, как у проектов.
///
/// Взамен получено бесплатно то, за что своя плита платила бы кодом: стрелки,
/// Return, Esc, набор букв, переворот у края экрана, выход за границу окна и
/// роль «меню» для VoiceOver.
///
/// Владелец — **надпись, а не кнопка**: у него нет ни одного действия (убрать
/// нельзя, `plan-people.md` §6), а кнопка, которая ничего не делает, — тупик по
/// `design/no-dead-ends.md`.
struct ParticipantsMenu: View {
    let model: MeetingPane.Meta.People

    var body: some View {
        Section("Участники") {
            ForEach(model.rows) { row in
                if row.isRemovable {
                    // Подменю на участника, а не общий список «Убрать ▸»: там
                    // те же имена стояли бы вторым списком, и с приходом
                    // переименования — третьим.
                    Menu(row.name) {
                        Button("Убрать") { model.remove(row) }
                    }
                } else {
                    Text(row.name)
                }
            }
        }
        // Пусто — пункта нет вовсе. Подменю без пунктов открывается в никуда, а
        // это тупик; печатать нового человека пока негде (см. доккоммент).
        if !model.candidates.isEmpty {
            Divider()
            Menu("Добавить") {
                ForEach(model.candidates, id: \.self) { name in
                    Button(name) { model.add(name) }
                }
            }
        }
    }
}
