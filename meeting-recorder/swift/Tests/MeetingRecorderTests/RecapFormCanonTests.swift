import XCTest
@testable import PropellerPure

/// Каждая строка ниже — из живого архива (замер 2026-08-27, 73 конспекта):
/// разметка, в которой имя человека стоит, а разбор его не достаёт.
final class RecapFormCanonTests: XCTestCase {

    private let roster = ["Левон", "Вячеслав Киржаев", "Владислав Шукуров", "Marina Primer"]

    private func canon(_ recap: String, roster: [String]? = nil) -> String {
        RecapFormCanon.canonical(recap, roster: roster ?? self.roster).recap
    }

    // MARK: - Ответственный

    /// 9 пунктов из 186: двоеточие вместо тире.
    func testДвоеточиеСтановитсяТире() {
        let out = canon("## Задачи\n- **Вячеслав Киржаев**: узнать у ребят про обезличку.\n")
        XCTAssertEqual(out, "## Задачи\n- **Вячеслав Киржаев** — узнать у ребят про обезличку.\n")
        XCTAssertEqual(
            RecapAtom.parse("**Вячеслав Киржаев** — узнать у ребят про обезличку.").assignee,
            "Вячеслав Киржаев"
        )
    }

    /// 14 пунктов из 186: имя есть, жирного нет.
    func testИмяБезЖирногоСтановитсяЖирным() {
        let out = canon("## Задачи\n- Владислав Шукуров — переодеть 2 функции «Праймер».\n")
        XCTAssertEqual(out, "## Задачи\n- **Владислав Шукуров** — переодеть 2 функции «Праймер».\n")
    }

    func testДефисМеждуИменемИДеломСтановитсяТире() {
        XCTAssertEqual(
            canon("## Задачи\n- **Левон** - прислать доки.\n"),
            "## Задачи\n- **Левон** — прислать доки.\n"
        )
    }

    /// Написание берётся из состава, а не из текста: тот же канон, что у
    /// `PersonCanon`, — иначе один человек уезжает в архив двумя способами.
    func testНаписаниеБерётсяИзСостава() {
        XCTAssertEqual(
            canon("## Задачи\n- Марина — собрать смету.\n"),
            "## Задачи\n- **Marina** — собрать смету.\n"
        )
    }

    /// Вся заслонка модуля. «Обед» и «Команда» — не люди, и делать их
    /// ответственными хуже, чем оставить задачу без имени.
    func testИмениВнеСоставаНеПоявляется() {
        let role = "## Задачи\n- Команда — обсудить с клиентом стек.\n"
        XCTAssertEqual(canon(role), role)
        let thing = "## Задачи\n- Обед — перенести на 14:00.\n"
        XCTAssertEqual(canon(thing), thing)
    }

    /// Состав пуст — журнал окна молчал; имён модуль не касается вовсе.
    func testБезСоставаИменаНеТрогаются() {
        let line = "## Задачи\n- Левон — прислать доки.\n"
        XCTAssertEqual(canon(line, roster: []), line)
    }

    /// Дефис живёт внутри фамилий и слов: по нему не рвём.
    func testПоДефисуСтрокаНеРвётся() {
        let line = "## Задачи\n- Веб-стор — проверить выкладку.\n"
        XCTAssertEqual(canon(line), line)
    }

    /// `**Имя** глагол` без разделителя оставлен модели сознательно: отличить
    /// исполнителя от жирного начала фразы можно только по следующему слову.
    func testБезРазделителяНеДодумываем() {
        let line = "## Задачи\n- **Левон** проверяет инструменты генерации.\n"
        XCTAssertEqual(canon(line), line)
    }

    /// Двоеточие берётся самое левое — иначе в имя уехала бы половина пункта.
    func testДвоеточиеИзСерединыФразыНеСтановитсяИменем() {
        let line = "## Задачи\n- Собрать смету — учесть скидку: она уже согласована.\n"
        XCTAssertEqual(canon(line), line)
    }

    // MARK: - Голова решения

    /// 135 пунктов архива из 243 с ведущим жирным. Ярлык из двух и больше слов
    /// над целой фразой — заголовок, а не решение.
    func testРубрикаИзДвухСловСнимаетсяЦеликом() {
        let out = canon("""
        ## Решения
        - **Связи вместо статических страниц:** Каждая единица контента рассматривается как узел графа.
        """)
        XCTAssertTrue(out.contains(
            "- Каждая единица контента рассматривается как узел графа."
        ), out)
        XCTAssertFalse(out.contains("Связи вместо"))
    }

    /// Двоеточие бывает и снаружи звёздочек — та же голова.
    func testДвоеточиеСнаружиЗвёздочекТожеЯрлык() {
        let out = canon("## Решения\n- **Формат разработки**: Отказ от полной пересборки визуальной части.\n")
        XCTAssertEqual(out, "## Решения\n- Отказ от полной пересборки визуальной части.\n")
    }

    /// Однословный ярлык и человек с этой стороны выглядят одинаково, а цена
    /// ошибки перевёрнута: потерять человека хуже, чем оставить рубрику.
    func testОднословныйЯрлыкТолькоТеряетЖирное() {
        XCTAssertEqual(
            canon("## Решения\n- **Сроки:** Ориентир — завершение разработки к середине сентября.\n"),
            "## Решения\n- Сроки: Ориентир — завершение разработки к середине сентября.\n"
        )
        XCTAssertEqual(
            canon("## Решения\n- **Ирина:** Убирает слайд про Discovery из презентации.\n"),
            "## Решения\n- Ирина: Убирает слайд про Discovery из презентации.\n"
        )
    }

    /// Заглавная внутри, латиница или цифра — ярлык называет проект или
    /// человека, и без него пункт теряет, о чём он.
    func testСущностьВГоловеОстаётся() {
        XCTAssertEqual(
            canon("## Решения\n- **ГПН (Дом пряжи)**: Проект прокинут на следующую неделю после встречи.\n"),
            "## Решения\n- ГПН (Дом пряжи): Проект прокинут на следующую неделю после встречи.\n"
        )
        XCTAssertEqual(
            canon("## Решения\n- **Работа Ильяса на Music:** Левон рекомендует использовать сильные стороны команды.\n"),
            "## Решения\n- Работа Ильяса на Music: Левон рекомендует использовать сильные стороны команды.\n"
        )
    }

    /// Имя из состава не трогается никогда, даже двухсловное.
    func testИмяИзСоставаВГоловеНеСнимается() {
        XCTAssertEqual(
            canon("## Решения\n- **Вячеслав Киржаев:** Берёт на себя разговор с руководителем о обезличке.\n"),
            "## Решения\n- Вячеслав Киржаев: Берёт на себя разговор с руководителем о обезличке.\n"
        )
    }

    /// Обрывок хуже рубрики: «**Сроки:** к сентябрю» без головы не читается.
    func testКороткийОстатокОставляетЯрлык() {
        XCTAssertEqual(
            canon("## Решения\n- **Сроки проекта:** к середине сентября.\n"),
            "## Решения\n- Сроки проекта: к середине сентября.\n"
        )
    }

    /// Форма поручения: жирное уходит, имя остаётся на месте вместе с тире —
    /// ровно то, что видит человек на вкладке «Решения» (`ProjectScreen`).
    func testФормаПорученияТеряетТолькоЖирное() {
        XCTAssertEqual(
            canon("## Решения\n- **Ирина** — убрать слайд про Discovery из презентации.\n"),
            "## Решения\n- Ирина — убрать слайд про Discovery из презентации.\n"
        )
    }

    /// Разбор после правки не находит у решения ответственного — та самая
    /// причина, по которой правило заведено.
    func testПослеПравкиУРешенияНетОтветственного() {
        let out = canon("## Решения\n- **Ирина** — убрать слайд про Discovery из презентации.\n")
        let item = out.components(separatedBy: "- ")[1].trimmingCharacters(in: .newlines)
        XCTAssertNil(RecapAtom.parse(item).assignee)
    }

    /// И линтер на приведённом тексте молчит: находка `decisionTopicLabel`
    /// требует звёздочек, а их не остаётся ни в одной из четырёх голов.
    func testПослеПравкиЛинтерНеВидитЯрлыков() {
        let recap = """
        ## Решения
        - **Связи вместо статических страниц:** Каждая единица контента рассматривается как узел графа.
        - **Сроки:** Ориентир — завершение разработки к середине сентября.
        - **ГПН (Дом пряжи)**: Проект прокинут на следующую неделю после встречи.
        - **Ирина** — убрать слайд про Discovery из презентации.
        """
        let before = RecapLint.findings(recap: recap, transcript: "")
        XCTAssertEqual(before.filter { $0.kind == .decisionTopicLabel }.count, 3)
        XCTAssertEqual(before.filter { $0.kind == .decisionAsTask }.count, 1)
        let after = RecapLint.findings(recap: canon(recap), transcript: "")
        XCTAssertTrue(after.filter { $0.kind == .decisionTopicLabel }.isEmpty)
        XCTAssertTrue(after.filter { $0.kind == .decisionAsTask }.isEmpty)
    }

    /// Жирное в середине пункта — настоящее выделение («**«VK Кость»**»,
    /// «**Propeller 2.0**»), 14 случаев архива, и оно остаётся.
    func testЖирноеВСерединеПунктаОстаётся() {
        let line = "## Решения\n- Утвердили сокращённое название **«VK Кость»** вместо «ВК Контекст».\n"
        XCTAssertEqual(canon(line), line)
    }

    /// «Задачи» этим правилом не трогаются: там жирный ответственный — канон.
    func testЗадачиГоловойРешенияНеТрогаются() {
        let line = "## Задачи\n- [ ] **Левон** — прислать доки.\n"
        XCTAssertEqual(canon(line), line)
    }

    // MARK: - «Итог» одним абзацем

    /// Решение владельца 2026-08-27: описание встречи под её названием — ровно
    /// один абзац. В живом архиве их больше одного у 17 конспектов из 139.
    func testДваАбзацаИтогаСклеиваютсяВОдин() {
        let recap = """
        ## Итог

        Левон и Владислав обсудили передачу работы разработчикам.

        Они уточнили формат взаимодействия с клиентами.

        ## Решения
        - Отказались от диплинков.
        """
        let out = canon(recap)
        XCTAssertTrue(out.contains(
            "Левон и Владислав обсудили передачу работы разработчикам. Они уточнили формат взаимодействия с клиентами."
        ))
        // Ни одного слова не потеряно, и следующий раздел на месте.
        XCTAssertTrue(out.contains("## Решения"))
        XCTAssertTrue(out.contains("- Отказались от диплинков."))
    }

    func testОдинАбзацИтогаНеТрогается() {
        let recap = "## Итог\n\nВстреча про смету.\n\n## Решения\n- Отказались от диплинков.\n"
        XCTAssertEqual(canon(recap), recap)
    }

    /// Четыре абзаца — тоже живой случай архива.
    func testЧетыреАбзацаТожеСклеиваются() {
        let recap = "## Итог\n\nРаз.\n\nДва.\n\nТри.\n\nЧетыре.\n"
        XCTAssertEqual(canon(recap), "## Итог\n\nРаз. Два. Три. Четыре.\n")
    }

    /// Список внутри «Итога» останавливает правило: склеить пункты в абзац —
    /// это переписывание, а не форматирование.
    func testСписокВИтогеОстанавливаетСклейку() {
        let recap = "## Итог\n\nВстреча про смету.\n\n- Первый пункт.\n- Второй пункт.\n"
        XCTAssertEqual(canon(recap), recap)
    }

    /// Заголовок ведущего раздела бывает и «Итоги», и «Summary» — те же имена,
    /// что знает `SummaryDocument.leadHeadings`.
    func testИтогиИSummaryТожеВедущийРаздел() {
        XCTAssertEqual(canon("## Итоги\n\nРаз.\n\nДва.\n"), "## Итоги\n\nРаз. Два.\n")
        XCTAssertEqual(canon("## Summary\n\nOne.\n\nTwo.\n"), "## Summary\n\nOne. Two.\n")
    }

    /// Абзацы «Решений» и «Хода обсуждения» — не наше дело: там их сколько
    /// написано, столько и надо.
    func testАбзацыДругихРазделовНеСклеиваются() {
        let recap = "## Ход обсуждения\n\nПервая тема.\n\nВторая тема.\n"
        XCTAssertEqual(canon(recap), recap)
    }

    /// Склейка и починка имени в одном проходе, и обе цитаты уходят наружу.
    func testСклейкаИИмяЧинятсяВместе() {
        let result = RecapFormCanon.canonical(
            "## Итог\n\nРаз.\n\nДва.\n\n## Задачи\n- Левон: прислать доки.\n",
            roster: roster
        )
        XCTAssertTrue(result.recap.contains("## Итог\n\nРаз. Два."))
        XCTAssertTrue(result.recap.contains("- **Левон** — прислать доки."))
        XCTAssertEqual(result.fixed, ["«Итог» из 2 абзацев", "Левон: "])
    }

    // MARK: - Чекбокс

    /// Чекбоксы модуль не расставляет: панель саммари рисует их буквальными
    /// скобками, и это открытый вопрос `plan-projects.md` §4.5, а не мелочь,
    /// которую можно закрыть из модуля про разметку.
    func testЧекбоксНеДописывается() {
        let bare = "## Задачи\n- обсудить flow демоскирования\n"
        XCTAssertEqual(canon(bare), bare)
    }

    /// Стоящий чекбокс — состояние, поставленное человеком: не трогается ни в
    /// ту, ни в другую сторону, и не мешает починить имя рядом с ним.
    func testСтоящийЧекбоксНеТрогается() {
        let done = "## Задачи\n- [x] **Левон** — написать Дену\n"
        XCTAssertEqual(canon(done), done)
        XCTAssertEqual(
            canon("## Задачи\n- [x] Левон: написать Дену\n"),
            "## Задачи\n- [x] **Левон** — написать Дену\n"
        )
    }

    // MARK: - Границы

    /// У решения не появляется ни ответственного, ни чекбокса — правило
    /// разметки задачи в «Решения» не заходит. Голова решения при этом своё
    /// жирное теряет: это другое правило, и оно про читателя, а не про разбор.
    func testПравилоЗадачиВРешенияНеЗаходит() {
        let recap = """
        ## Решения
        - **Левон**: утвердил новую структуру главной.
        - Левон — утвердил новую структуру главной.

        ## Задачи
        - Левон: прислать доки.
        """
        let out = canon(recap)
        XCTAssertTrue(out.contains("- Левон: утвердил новую структуру главной."))
        XCTAssertTrue(out.contains("- Левон — утвердил новую структуру главной."))
        XCTAssertFalse(out.contains("[ ]"))
        XCTAssertTrue(out.contains("- **Левон** — прислать доки."))
    }

    /// Секции ниже «Задач» тоже свои: правка не должна уехать в «Открытые
    /// вопросы» и в «Ход обсуждения».
    func testСледующаяСекцияЗакрываетЗадачи() {
        let recap = """
        ## Задачи
        - Левон: прислать доки.

        ## Открытые вопросы
        - Левон: кто платит за прод.
        """
        let out = canon(recap)
        XCTAssertTrue(out.contains("- **Левон** — прислать доки."))
        XCTAssertTrue(out.contains("- Левон: кто платит за прод."))
    }

    /// Заголовок приезжает и болдом, и с хвостовым пробелом — часть текста
    /// пишет модель, а не наш сборщик (тот же довод, что у `RecapDigest`).
    func testЗаголовокБолдомИСХвостом() {
        XCTAssertEqual(
            canon("## **Задачи**  \n- Левон: прислать доки.\n"),
            "## **Задачи**  \n- **Левон** — прислать доки.\n"
        )
    }

    /// Виндовые окончания строк уже однажды порвала правка, которая о них не
    /// знала (`63af1d9`).
    func testВиндовыеОкончанияСтрокВыживают() {
        XCTAssertEqual(
            canon("## Задачи\r\n- Левон: прислать доки.\r\n"),
            "## Задачи\r\n- **Левон** — прислать доки.\r\n"
        )
    }

    /// Форма не меняется: `polished` сравнивает `RecapLint.shape` до и после, и
    /// сдвиг числа пунктов прочитался бы как потеря содержания.
    func testФормаНеМеняется() {
        let recap = """
        ## Задачи
        - Левон: прислать доки.
        - обсудить flow

        ## Прочее
        Абзац без маркера.
        """
        XCTAssertEqual(RecapLint.shape(of: recap), RecapLint.shape(of: canon(recap)))
    }

    /// Что переписали — говорится вслух, как у `RecapLint.Grounding.removed`.
    func testЦитатыПравокВозвращаются() {
        let result = RecapFormCanon.canonical(
            "## Задачи\n- Левон: прислать доки.\n- обсудить flow\n", roster: roster
        )
        XCTAssertEqual(result.fixed, ["Левон: "])
    }

    /// Живой прогон 2026-08-27 (`tools/recap-lab`, встреча 20260806_103119,
    /// после редактуры): редактор снял жирное с трёх исполнителей подряд. Канон
    /// возвращает его двум участникам состава и **не возвращает** «Команде
    /// дизайна» — её в составе нет, и делать её ответственной хуже, чем оставить
    /// задачу без имени. Это и есть тот случай, ради которого модуль заведён.
    func testРедакторСнялЖирноеАКанонВернул() {
        let recap = """
        ## Задачи
        - [ ] Левон — проверить работу нового текста с пояснениями в Figma.
        - [ ] Команда дизайна — создать макет версии плеера с розовыми акцентами.
        - [ ] Левон — протестировать интеграцию видео в ленту истории.
        """
        let out = canon(recap)
        XCTAssertEqual(out.components(separatedBy: "- [ ] **Левон** — ").count - 1, 2)
        XCTAssertTrue(out.contains("- [ ] Команда дизайна — создать макет"))
    }

    /// Второй прогон ничего не меняет: канон — неподвижная точка.
    func testПовторныйПрогонНичегоНеМеняет() {
        let once = canon("## Задачи\n- Левон: прислать доки.\n- Команда — обсудить стек.\n")
        XCTAssertEqual(canon(once), once)
    }
}
