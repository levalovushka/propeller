    /// Живой прогон 2026-08-27 (`tools/recap-lab`, встреча 20260806_103119,
    /// после редактуры): редактор снял жирное с трёх исполнителей подряд. Канон
    /// возвращает его двум участникам состава и **не возвращает** «Команде
    /// дизайна» — её в составе нет, и делать её ответственной хуже, чем оставить
    /// задачу без имени. Это и есть тот случай, ради которого модуль заведён.
    func testРедакторСнялЖирноеАКанонВернул() {
        let recap = """
        ## Задачи
        - [ ] Левон — проверить работу нового текста с пояснениями в Figma.
        - [ ] Команда дизайна — создать макет версии плеера с розовыми акцентами.
        - [ ] Левон — протестировать интеграцию видео в ленту истории.
        """
        let out = canon(recap)
        XCTAssertEqual(out.components(separatedBy: "- **Левон** — ").count - 1, 2)
        XCTAssertTrue(out.contains("- Команда дизайна — создать макет"))
    }

    /// Второй прогон ничего не меняет: канон — неподвижная точка.
    func testПовторныйПрогонНичегоНеМеняет() {
        let once = canon("## Задачи\n- Левон: прислать доки.\n- Команда — обсудить стек.\n")
        XCTAssertEqual(canon(once), once)
    }
